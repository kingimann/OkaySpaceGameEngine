TextEncoding EncodingForLabel(const std::string& label) {
    const std::string l = okay::str::LowerAscii(okay::str::Trim(label));
    if (l.empty() || l.size() > 24) return TextEncoding::Unknown;
    for (const Label& x : kLabels) if (l == x.label) return x.enc;
    return TextEncoding::Unknown;
}

