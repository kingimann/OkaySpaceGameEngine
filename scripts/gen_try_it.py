#!/usr/bin/env python3
"""Assemble docs/try_it.md from one small file per entry in docs/try_it/.

Why: every change used to append a row and a section at the END of one big file, so two open PRs always conflicted.
Now a change adds ONE NEW FILE under docs/try_it/ and never touches docs/try_it.md, so PRs cannot conflict.

Entry file (docs/try_it/<id>-<slug>.md):

    ---
    id: 7zz
    group: main                 (optional: main | switches | appendix; default main)
    row: | 7zz | What | Where to reach it in the release | Status |      (optional: the line in the index table)
    ---
    ## 7zz. Heading of the section
    ...the section text (what it is, steps, what you should see, what was and was not verified)...

An entry needs a `row`, a body, or both. `docs/try_it/_header.md` is the text above the index table.
Output is deterministic: header, banner, index table (sorted), then the bodies (sorted). Sort order is the group
(main, switches, appendix), then the id read naturally (7 < 7b < 7zh < 16), then the file name.

Usage:
    python3 scripts/gen_try_it.py                # write docs/try_it.md (also the way to resolve a merge conflict in it)
    python3 scripts/gen_try_it.py --check        # entries are valid AND docs/try_it.md is up to date (exit 1 if not)
    python3 scripts/gen_try_it.py --check-entries  # entries are valid only (what PR CI runs; PRs do not commit the page)
    python3 scripts/gen_try_it.py --new ID "Title"  # create a starter entry file

Written from our own design (docs/try_it/README.md); standard library only.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENTRY_DIR = os.path.join(ROOT, "docs", "try_it")
OUT = os.path.join(ROOT, "docs", "try_it.md")
GROUPS = ("main", "switches", "appendix")
ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
BANNER = ("<!-- GENERATED by scripts/gen_try_it.py from docs/try_it/*.md. Do NOT edit this file: add or change a file in "
          "docs/try_it/ and run `python3 scripts/gen_try_it.py`. If this file has merge conflict markers, run that command "
          "and `git add docs/try_it.md`; that is the whole resolution. See docs/try_it/README.md. -->")
TABLE_HEAD = ["## The list", "", "| # | What | Where to reach it in the release | Status |", "|---|---|---|---|"]


def natural(s):
    return tuple((0, int(p), "") if p.isdigit() else (1, 0, p.lower()) for p in re.findall(r"\d+|[A-Za-z]+|[^A-Za-z\d]+", s))


def parse_entry(path):
    """Return (meta dict, body str). Raises ValueError with a readable message."""
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    name = os.path.relpath(path, ROOT)
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{name}: must start with a '---' front matter line (id: ...)")
    meta, i = {}, 1
    while i < len(lines) and lines[i].strip() != "---":
        m = re.match(r"^([a-z_]+):\s?(.*)$", lines[i])
        if not m:
            raise ValueError(f"{name}:{i + 1}: front matter line must be 'key: value', got {lines[i]!r}")
        meta[m.group(1)] = m.group(2).rstrip()
        i += 1
    if i >= len(lines):
        raise ValueError(f"{name}: front matter is not closed by a second '---' line")
    body = "\n".join(lines[i + 1:]).strip("\n")
    meta["_file"] = os.path.basename(path)
    return meta, body


def validate(meta, body):
    f = meta["_file"]
    unknown = set(meta) - {"id", "group", "row", "_file"}
    if unknown:
        raise ValueError(f"{f}: unknown front matter key(s) {sorted(unknown)} (allowed: id, group, row)")
    eid = meta.get("id", "")
    if not ID_RE.match(eid):
        raise ValueError(f"{f}: id {eid!r} is missing or not letters, digits, dot, dash or underscore")
    if meta.get("group", "main") not in GROUPS:
        raise ValueError(f"{f}: group must be one of {GROUPS}")
    row = meta.get("row")
    if row is not None:
        if not row.startswith("|") or not row.rstrip().endswith("|") or len(row.strip().strip("|").split(" | ")) != 4:
            raise ValueError(f"{f}: row must be one table line with 4 cells: | id | What | Where | Status |")
        if not row.startswith(f"| {eid} |"):
            raise ValueError(f"{f}: row must start with '| {eid} |' (the entry id)")
    if row is None and not body.strip():
        raise ValueError(f"{f}: entry has neither a row nor a body")
    if body and not body.lstrip().startswith("#"):
        raise ValueError(f"{f}: the body must start with a heading line (## {eid}. Title)")


def load_entries():
    if not os.path.isdir(ENTRY_DIR):
        raise ValueError("docs/try_it/ does not exist")
    entries, seen = [], {}
    for fn in sorted(os.listdir(ENTRY_DIR)):
        if not fn.endswith(".md") or fn.startswith("_") or fn == "README.md":
            continue
        meta, body = parse_entry(os.path.join(ENTRY_DIR, fn))
        validate(meta, body)
        if meta["id"] in seen:
            raise ValueError(f"{fn}: id {meta['id']!r} is already used by {seen[meta['id']]}. Pick another id.")
        seen[meta["id"]] = fn
        meta["group"] = meta.get("group", "main")
        entries.append((meta, body))
    entries.sort(key=lambda e: (GROUPS.index(e[0]["group"]), natural(e[0]["id"]), e[0]["_file"]))
    return entries


def assemble():
    with open(os.path.join(ENTRY_DIR, "_header.md"), encoding="utf-8") as f:
        header = f.read().strip("\n").split("\n")
    entries = load_entries()
    out = [header[0], "", BANNER] + header[1:] + [""] + TABLE_HEAD
    out += [m["row"] for m, _ in entries if m.get("row")]
    out += ["", "---", ""]
    bodies = [b for _, b in entries if b.strip()]
    return "\n".join(out) + "\n" + "\n\n".join(bodies) + "\n"


def main(argv):
    try:
        if argv[:1] == ["--new"]:
            if len(argv) != 3 or not ID_RE.match(argv[1]):
                print('usage: gen_try_it.py --new ID "Title"', file=sys.stderr)
                return 2
            eid, title = argv[1], argv[2]
            slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:40]
            path = os.path.join(ENTRY_DIR, f"{eid}-{slug}.md")
            if os.path.exists(path):
                print(f"{path} exists", file=sys.stderr)
                return 1
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(f"---\nid: {eid}\nrow: | {eid} | {title} | Where to reach it in the release (menu, template, example scene, switch) | New in this change; what is unverified |\n---\n"
                        f"## {eid}. {title}\n\n**What it is.** One or two plain sentences.\n\n**Steps.**\n1. What to open or run.\n2. What to click or press.\n\n"
                        "**What you should see.** The result, and how to tell it worked.\n\n**Status.** Verified here / Tested on main / Unverified, said honestly.\n")
            print(f"created {os.path.relpath(path, ROOT)}; edit it, then run python3 scripts/gen_try_it.py")
            return 0
        text = assemble()
        if "--check-entries" in argv:
            print(f"try_it entries OK ({len(load_entries())} entries)")
            return 0
        if "--check" in argv:
            cur = ""
            if os.path.exists(OUT):
                with open(OUT, encoding="utf-8") as f:
                    cur = f.read()
            if cur != text:
                print("docs/try_it.md is out of date (or has conflict markers). Run: python3 scripts/gen_try_it.py", file=sys.stderr)
                return 1
            print("docs/try_it.md is up to date")
            return 0
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote docs/try_it.md from {len(load_entries())} entries")
        return 0
    except ValueError as e:
        print(f"gen_try_it: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
