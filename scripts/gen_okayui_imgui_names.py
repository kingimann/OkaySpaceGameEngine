#!/usr/bin/env python3
"""Writes okayui/include/okay/UI/OkayUIImGuiNames.hpp: the Dear ImGui spellings of types, flags and enumerators that OkayUI has under
other names (ImGuiCol_Button -> Col_Button, ImGuiWindowFlags_NoMove -> Window_NoMove, ...), found with the same matching rules as
scripts/imgui_usage_report.py. The header is for code compiled WITHOUT imgui.h (a port probe, a future port); it does nothing when
imgui.h is included first. Run it after changing the OkayUI headers; `--check` exits 1 when the file is stale.
Written from the names only; no Dear ImGui text is read."""
import importlib.util, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("usage", os.path.join(HERE, "imgui_usage_report.py"))
usage = importlib.util.module_from_spec(spec); spec.loader.exec_module(usage)
OUT = os.path.join(usage.ROOT, "okayui", "include", "okay", "UI", "OkayUIImGuiNames.hpp")

# Defined by hand in the preamble (or by OkayUI itself), so not generated.
HAND = {"ImVec2", "ImU32", "ImDrawList"}
# Typedef'd to int, as Dear ImGui does for the ids that are passed around as plain numbers.
AS_INT = {"ImGuiCol", "ImGuiCond", "ImGuiStyleVar", "ImGuiMouseButton", "ImGuiDir", "ImGuiSortDirection"}
# Names that already exist in namespace OkayUI under the same spelling.
SAME_SPELLING_TYPES = {"ImVec4", "ImTextureID", "ImRect", "ImGuiID"}

PREAMBLE = r'''#pragma once
// GENERATED by scripts/gen_okayui_imgui_names.py from the OkayUI headers; do not edit. The Dear ImGui spellings of types, flags and
// enumerators that OkayUI has under other names, for code compiled without imgui.h (the port probe, a future port). When imgui.h is
// included first this header does nothing. See docs/own_ui_toolkit.md section 6.13.
#ifndef IMGUI_VERSION
#include "okay/UI/OkayUI.hpp"
#include "okay/UI/OkayUICompat.hpp"
#include "okay/UI/OkayUIInternals.hpp"
#include "okay/UI/OkayUIDock.hpp"
#include "okay/UI/OkayUIDockBuilder.hpp"
#include <cstdint>

// ImVec2: two floats that convert to and from OkayUI::Vec2 (the hand-written part; own code).
struct ImVec2 {
    float x = 0.0f, y = 0.0f;
    ImVec2() {}
    ImVec2(float x_, float y_) : x(x_), y(y_) {}
    ImVec2(const OkayUI::Vec2& v) : x(v.x), y(v.y) {}
    operator OkayUI::Vec2() const { return OkayUI::Vec2{x, y}; }
    float& operator[](int i) { return i ? y : x; }
    float operator[](int i) const { return i ? y : x; }
};
#ifdef IMGUI_DEFINE_MATH_OPERATORS
inline ImVec2 operator+(const ImVec2& a, const ImVec2& b) { return ImVec2(a.x + b.x, a.y + b.y); }
inline ImVec2 operator-(const ImVec2& a, const ImVec2& b) { return ImVec2(a.x - b.x, a.y - b.y); }
inline ImVec2 operator*(const ImVec2& a, float f) { return ImVec2(a.x * f, a.y * f); }
inline ImVec2 operator/(const ImVec2& a, float f) { return ImVec2(a.x / f, a.y / f); }
inline ImVec2& operator+=(ImVec2& a, const ImVec2& b) { a.x += b.x; a.y += b.y; return a; }
inline ImVec2& operator-=(ImVec2& a, const ImVec2& b) { a.x -= b.x; a.y -= b.y; return a; }
#endif
typedef unsigned int ImU32;
typedef unsigned char ImU8;
typedef unsigned short ImU16;
typedef unsigned long long ImU64;
typedef signed char ImS8;
typedef short ImS16;
typedef int ImS32;
typedef long long ImS64;
typedef OkayUI::DrawList ImDrawList;
#define IM_COL32(R, G, B, A) (OkayUI::RGBA((R), (G), (B), (A)))
using OkayUI::ImVec4;
using OkayUI::ImTextureID;
using OkayUI::ImRect;
using OkayUI::ImGuiID;
using OkayUI::ImGuiStyle;
// Plain-int typedefs Dear ImGui code uses for flag arguments.
typedef int ImDrawFlags;

// The generated names.
'''

def declared_types():
    """(type names, enumerator names) declared in the OkayUI headers."""
    import re
    out = set(); enums = set()
    d = usage.API_DIR
    for fn in os.listdir(d):
        if fn.endswith(".hpp") and fn != "OkayUIImGuiNames.hpp":
            t = usage.strip_comments_and_strings(open(os.path.join(d, fn), encoding="utf-8", errors="replace").read())
            for m in re.finditer(r"\b(?:struct|class|enum)\s+(?:class\s+)?([A-Za-z_]\w*)", t): out.add(m.group(1))
            for m in re.finditer(r"\btypedef\s+[^;]*?\b([A-Za-z_]\w*)\s*;", t): out.add(m.group(1))
            for m in re.finditer(r"\busing\s+([A-Za-z_]\w*)\s*=", t): out.add(m.group(1))
            for m in re.finditer(r"\benum\b[^{;]*\{([^}]*)\}", t):
                for part in m.group(1).split(","):
                    mm = re.match(r"\s*([A-Za-z_]\w*)", part)
                    if mm: enums.add(mm.group(1))
    return out, enums


def main():
    tdecl, edecl = declared_types()
    funcs, idents, dlm, calls, types, dls, units, per_file = usage.scan()
    lines = []
    for name in sorted(types):
        if name in HAND or name in SAME_SPELLING_TYPES:
            continue
        ident = usage.resolve_type(name, idents)
        if not ident:
            continue
        if ident == name:
            if name not in SAME_SPELLING_TYPES:
                lines.append("using OkayUI::%s;" % name)
            continue
        if "_" in name:
            if ident not in edecl:
                continue
            lines.append("constexpr auto %s = OkayUI::%s;" % (name, ident))
        elif name in AS_INT or name.endswith("Flags"):
            lines.append("typedef int %s;" % name)
        elif ident in tdecl:
            lines.append("typedef OkayUI::%s %s;" % (ident, name))
    text = PREAMBLE + "\n".join(lines) + "\n\n// The namespace host code writes.\nnamespace ImGui = OkayUI;\n#endif // IMGUI_VERSION\n"
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("stale: run python3 scripts/gen_okayui_imgui_names.py"); sys.exit(1)
        print("up to date (%d generated names)" % len(lines)); return
    open(OUT, "w").write(text)
    print("wrote %s (%d generated names)" % (OUT, len(lines)))

main()
