// What each category is for (VsCat order).
inline const char* VsCatBlurb(int cat) {
    static const char* blurbs[] = {
        "Where a script starts. Every chain begins with an event: when the game starts, every frame, "
        "on a key press, a click, a collision or a message from another object.",
        "Control the order and timing: choose a path with Branch, wait, repeat, loop, run once, "
        "or only let the flow through every so often.",
        "Remember values while the game runs: numbers, text or true/false on this object, "
        "variables on other objects, and saved values that survive a restart.",
        "Work with numbers and 3D vectors: arithmetic, rounding, random numbers, easing, "
        "trigonometry, distances and directions.",
        "True / false questions: compare values, combine conditions with And / Or / Not, "
        "or pick between two values.",
        "Read the player and the clock: keys, mouse buttons and position, the movement axes, "
        "time, frame count and this object's speed.",
        "Where things are: read and set position, rotation and scale, move or turn objects, "
        "and find objects by name or tag.",
        "Make things happen: print, play sounds and animations, spawn and destroy objects, "
        "push with physics, change colour, text and UI, switch scenes.",
        "Values and text: fixed values, building and editing text, converting numbers to text, "
        "and the data that arrives with events and collisions.",
        "Online play and Steam: host or join a game, sync variables, send messages and RPCs, "
        "spawn networked objects, achievements, stats and leaderboards.",
        "The engine API C#-style scripts use, as nodes: GameObject, Transform, Rigidbody, Vector3, "
        "Input, Time, Mathf and Debug. Each node does exactly what its line of script does.",
    };
    return (cat >= 0 && cat < (int)(sizeof blurbs / sizeof blurbs[0])) ? blurbs[cat] : "";
}

inline const char* VsStepCatBlurb(bool cond) {
    return cond ? "Ready-made checks (Is Grounded, Has Tag, Is Visible...) that branch into True / False "
                  "without wiring any math."
                : "Ready-made steps (Move, Jump, Play Sound, Show Message...) you can drop in and set up "
                  "in the node, no wiring needed.";
}

