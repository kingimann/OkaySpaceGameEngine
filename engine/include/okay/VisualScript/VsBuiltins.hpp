#pragma once
// One visual-script node per text-script builtin (`Fn.print`, `Fn.move`, ...),
// plus the generic escape hatches (property, method, component, find, message,
// text snippet). The builtin nodes call OkayScriptVM::CallBuiltin, so a graph
// can do anything a .okay script can do.
#include "okay/VisualScript/NodeGraph.hpp"
#include "okay/VisualScript/VsTypes.hpp"
#include <memory>
#include <string>
#include <vector>

namespace okay::vs {

struct BuiltinNodeInfo {
    std::string type;      ///< "Fn.print"
    std::string title;     ///< "print"
    std::string builtin;   ///< "print"
};

/// Every text-script builtin, as a node. Built once.
const std::vector<BuiltinNodeInfo>& BuiltinNodes();
/// True for "Fn.<builtin>".
bool IsBuiltinNode(const std::string& type);
/// The node, or nullptr when `type` is neither a builtin node nor an escape hatch.
/// `args` is the text after the type (a property path, Type.Method, a message, a snippet).
std::unique_ptr<VsNode> MakeCoverageNode(const std::string& type, const std::vector<std::string>& args);
/// The most inputs a Fn.* node has (capsule_cast3 reads 13 arguments).
constexpr int kBuiltinMaxPins = 13;
/// How many inputs the node of text-script builtin `builtin` has: one per argument its code
/// reads, and never fewer than four (every Fn.* node had four before, so saved graphs keep
/// their pins). "dist3" -> 6, "print" -> 4.
int BuiltinPinCount(const std::string& builtin);
/// Label of argument input `pin`: "First", "Second" ... "Thirteenth" ("" outside the range).
const char* BuiltinPinName(int pin);

/// What the docs say about one builtin: its arguments in order, what it does and what it gives back.
/// Generated by tools/gen_fn_pin_docs.py into VsBuiltinDocs.gen.hpp (#888 finding 34, part C).
struct BuiltinDoc {
    const char* name;      ///< "raycast"
    const char* summary;   ///< one line; "" when the source has none
    const char* returns;   ///< what it gives back; "" when the source does not say
    const char* source;    ///< where the names came from ("docs/scripting_reference.md", "alias of raycast", ...)
    int argc;              ///< documented arguments, never more than pinCount
    unsigned optional;     ///< bit i set: argument i may be left empty
    int pinCount;          ///< BuiltinPinCount(name) when the table was generated
    const char* args[kBuiltinMaxPins];     ///< raw argument names as the text script writes them ("ox", "maxDist")
    const char* labels[kBuiltinMaxPins];   ///< the node's input labels, one per pin ("Origin Across", ..., "Sixth")
};
/// The docs of builtin `builtin` ("raycast", not "Fn.raycast"), or nullptr when none of the sources
/// names its arguments.
const BuiltinDoc* BuiltinDocFor(const std::string& builtin);
/// Every documented builtin, sorted by name.
const BuiltinDoc* BuiltinDocsBegin();
const BuiltinDoc* BuiltinDocsEnd();
/// Label of input `pin` of the node of `builtin`: the argument in words when the docs name it
/// ("Origin Across" for raycast's ox), else BuiltinPinName(pin). Only the label changes: graphs
/// save pins by index, so a saved graph loads the same.
const char* BuiltinPinName(const std::string& builtin, int pin);
/// Pin signature of "Fn.<builtin>": BuiltinPinCount optional inputs (Any), one result.
const NodeSignature& BuiltinSignatureFor(const std::string& type);

/// System-level coverage (FEATURE_MAP area, how a graph reaches it, the node).
std::string CoverageTableMarkdown();

} // namespace okay::vs
