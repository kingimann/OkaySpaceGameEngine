#pragma once
#include "okay/Scene/Component.hpp"
#include "okay/Scene/Transform.hpp"
#include <cstdint>
#include <memory>
#include <typeinfo>
#include <string>
#include <type_traits>
#include <vector>

namespace okay {

/// A named container of Components living in a Scene — the engine's primary
/// unit of composition, modeled directly on GameObject.
class GameObject {
public:
    std::string name;
    /// This object's own on/off flag ("activeSelf"). Inactive GameObjects are skipped
    /// by Update, Render and physics, and so are their children: what the engine
    /// tests is ActiveInHierarchy(), which also looks at every parent.
    bool active = true;
    /// Scene bookkeeping: the `active` value last reported to OnEnable/OnDisable
    /// (-1 = not seen yet, so the first frame never fires either).
    signed char activeSeen = -1;
    /// Optional tag for lookups (see Scene::FindWithTag).
    std::string tag;
    /// Runtime-only object (generated by a component, e.g. CraftingMenu's buttons):
    /// never written by the scene serializer, so saving and loading can't duplicate it.
    bool transient = false;
    /// If this object was instantiated from a .okayprefab file, the path to that
    /// file (empty otherwise). Links the instance to its source prefab so the
    /// editor can Apply changes back, Revert to the saved prefab, or reload every
    /// instance when the prefab file changes. Only the instance ROOT carries it.
    std::string prefabSource;
    /// Render/physics layer (0-31). A camera's cullingMask selects which layers it
    /// draws (bit 1<<layer); also used by the physics collision matrix.
    int layer = 0;
    /// Marked non-moving. A hint for tools/builds; objects flagged
    /// static are not expected to move at runtime.
    bool isStatic = false;

    /// Editor-only: locked objects can't be click-selected or dragged in the Scene
    /// view (pick them via the Hierarchy). Protects backdrops/ground from stray
    /// clicks while arranging things on top. No runtime effect; persisted.
    bool editorLocked = false;

    /// The name of the scene this object was MERGED in from (empty = it belongs to
    /// the main/host scene). Set when combining scenes so the editor's Hierarchy can
    /// show where each merged scene starts and ends. Persisted with the scene.
    std::string sourceScene;

    /// Per-object UI layering override. 0 = use the widget's default type layer
    /// (the historic per-type pass order); any non-zero value places this widget in
    /// the single UI draw pass by this key instead (higher = drawn later / on top),
    /// letting non-nested widgets of different types be layered freely. Ignored by
    /// non-UI objects. Hierarchy pre-order breaks ties.
    int uiDrawOrder = 0;

    /// First-person viewmodel flag. A camera that is told to IGNORE this object's
    /// owner (the local player, via Camera::ignoreObject) normally skips the whole
    /// player subtree — that's how you don't see your own body in first person.
    /// Objects flagged here are the EXCEPTION: they render for the owner's own camera
    /// even though they live inside the ignored subtree — exactly the Minecraft/Unturned
    /// "viewmodel": the body is hidden from the owner only, while the arm (this flag)
    /// stays visible to the owner. Other cameras (remote players) don't ignore this
    /// player at all, so they see the full body regardless of this flag.
    bool firstPersonViewmodel = false;

    /// A copy that exists only for the camera hiding this object's owner (the
    /// raised first-person arm). Colour passes draw it only for that camera.
    /// Shadow passes never draw it, so the copy cannot change another view.
    /// Not saved. The real body is a different object and is left alone.
    bool firstPersonOnly = false;

    /// A camera that ignores this object also skips this one. The real held
    /// prop uses it while the owner's viewmodel shows its own copy. Not saved.
    GameObject* ownerCameraSkip = nullptr;

    /// Every GameObject has a Transform from birth.
    Transform* transform = nullptr;

    /// True when this object and every parent above it are active. A child of an
    /// inactive parent does not update, render or simulate even if its own `active`
    /// is true. Walks the parent chain (a few pointer reads for a normal hierarchy).
    bool ActiveInHierarchy() const {
        const GameObject* g = this;
        for (int guard = 0; g && guard < 4096; ++guard) {
            if (!g->active) return false;
            const Transform* p = g->transform ? g->transform->Parent() : nullptr;
            g = p ? p->gameObject : nullptr;
        }
        return true;
    }

    /// Attach a new component of type T, forwarding constructor arguments.
    template <typename T, typename... Args>
    T* AddComponent(Args&&... args);

    /// Return the first attached component of type T, or nullptr.
    template <typename T>
    T* GetComponent() const;

    /// Return every attached component assignable to T.
    template <typename T>
    std::vector<T*> GetComponents() const;

    /// The first component of type T on this object or, failing that, any object below it
    /// (depth first, children in sibling order). Inactive objects are skipped, with
    /// their children, unless `includeInactive`.
    template <typename T>
    T* GetComponentInChildren(bool includeInactive = false) const;
    /// Every component of type T on this object and the objects below it (depth first).
    template <typename T>
    std::vector<T*> GetComponentsInChildren(bool includeInactive = false) const;
    /// The first component of type T on this object or one of its parents, nearest first.
    template <typename T>
    T* GetComponentInParent(bool includeInactive = false) const;

    /// Append every component assignable to T to `out` (no per-object allocation;
    /// used by Scene::FindObjectsOfType to avoid a temporary vector per object).
    template <typename T>
    void CollectComponents(std::vector<T*>& out) const;

    /// Iterate the attached components in their stored order.
    /// The reference is into this object's storage: do not AddComponent or
    /// RemoveComponent while a range-for is walking it. CopyComponentPointers
    /// is the list to walk when a callback might add components.
    const std::vector<std::unique_ptr<Component>>& Components() const { return m_components; }
    /// Pointers to the components in stored order, copied out of the vector.
    /// Adding a component can reallocate that vector; these pointers still
    /// refer to the component objects (they are individually heap-allocated).
    void CopyComponentPointers(std::vector<Component*>& out) const {
        out.clear();
        out.reserve(m_components.size());
        for (const auto& c : m_components) out.push_back(c.get());
    }
    /// Free every component except the Transform (used when the scene destroys
    /// the object: the shell stays alive so stale pointers never dangle).
    void StripToTransform() {
        for (std::size_t i = m_components.size(); i-- > 0;)
            if (m_components[i].get() != static_cast<Component*>(transform)) m_components.erase(m_components.begin() + (long)i);
        active = false;
        m_destroyed = true;
    }
    /// True once the scene destroyed this object (it's only a Transform shell now).
    bool IsDestroyed() const { return m_destroyed; }

    /// True if `other` is this object or any ancestor of it — used by cameras to skip
    /// a whole subtree (e.g. hiding the local player's body, rig parts included, from
    /// the first-person view without affecting other cameras).
    bool IsSelfOrDescendantOf(const GameObject* other) const;

    /// True when a camera whose ignore object is `camIgnore` should skip this
    /// object. A first-person-only copy is drawn solely for the camera that is
    /// hiding its owner. Any other object in that owner's subtree is skipped
    /// unless it is a viewmodel that camera is meant to see.
    bool HiddenFromCamera(const GameObject* camIgnore) const {
        if (firstPersonOnly)
            return !camIgnore || !IsSelfOrDescendantOf(camIgnore);
        if (ownerCameraSkip && camIgnore == ownerCameraSkip) return true;
        return camIgnore && IsSelfOrDescendantOf(camIgnore) && !firstPersonViewmodel;
    }

    /// Move `component` by `delta` positions within the stored order. Transform
    /// is pinned to index 0: the valid target range is [1, size-1], so neither the
    /// Transform itself nor any other component can be moved to index 0. Out-of-range
    /// moves or an unknown component are no-ops.
    void MoveComponent(Component* component, int delta);

    /// Remove a specific component (Transform cannot be removed). Returns true
    /// if it was found and removed.
    bool RemoveComponent(Component* component);
    /// Remove the first component of type T. Returns true if one was removed.
    template <typename T>
    bool RemoveComponent() {
        for (const auto& c : m_components)
            if (T* casted = dynamic_cast<T*>(c.get())) return RemoveComponent(casted);
        return false;
    }

    Scene* scene() const { return m_scene; }

    /// A number unique to this object for the whole run (never reused), so scripts
    /// can hold a reference that safely turns into "destroyed" instead of dangling.
    std::uint64_t InstanceId() const { return m_instanceId; }
    /// The live object with this id, or nullptr once it's gone (or destroyed).
    static GameObject* FromInstanceId(std::uint64_t id);

    ~GameObject();
    GameObject(const GameObject&) = delete;
    GameObject& operator=(const GameObject&) = delete;

private:
    friend class Scene;
    explicit GameObject(Scene* scene, std::string name);
    std::uint64_t m_instanceId = 0;

    /// Routes a freshly added component to the Scene's lifecycle queue.
    /// Defined in GameObject.cpp where the full Scene type is visible.
    void NotifyComponentAdded(Component* component);

    Scene* m_scene = nullptr;
    std::vector<std::unique_ptr<Component>> m_components;
    bool m_destroyed = false;
};

// ---- Template implementations -----------------------------------------

template <typename T, typename... Args>
T* GameObject::AddComponent(Args&&... args) {
    static_assert(std::is_base_of<Component, T>::value,
                  "T must derive from okay::Component");
    auto owned = std::make_unique<T>(std::forward<Args>(args)...);
    T* ptr = owned.get();
    ptr->gameObject = this;
    ptr->transform  = transform ? transform : dynamic_cast<Transform*>(ptr);
    m_components.push_back(std::move(owned));
    NotifyComponentAdded(ptr); // declared in Scene.hpp, defined in Scene.cpp
    return ptr;
}

// Component lookups run every frame all over the engine. Every object's first
// component is its Transform, so a lookup for a type that can't be a Transform
// starts after it (a bone object with nothing but a Transform then costs no
// dynamic_cast at all), and an exact type match skips the dynamic_cast walk.
template <typename T>
inline std::size_t FirstComponentToSearch(const std::vector<std::unique_ptr<Component>>& cs, const Transform* t) {
    if constexpr (std::is_base_of<T, Transform>::value) return 0;
    else return (!cs.empty() && cs[0].get() == static_cast<const Component*>(t)) ? 1 : 0;
}

template <typename T>
T* GameObject::GetComponent() const {
    for (std::size_t i = FirstComponentToSearch<T>(m_components, transform); i < m_components.size(); ++i) {
        Component* c = m_components[i].get();
        if (typeid(*c) == typeid(T)) return static_cast<T*>(c);
        if constexpr (!std::is_final<T>::value)   // a final type has no subclasses to find
            if (T* casted = dynamic_cast<T*>(c)) return casted;
    }
    return nullptr;
}

template <typename T>
std::vector<T*> GameObject::GetComponents() const {
    std::vector<T*> result;
    for (std::size_t i = FirstComponentToSearch<T>(m_components, transform); i < m_components.size(); ++i)
        if (T* casted = dynamic_cast<T*>(m_components[i].get())) result.push_back(casted);
    return result;
}

template <typename T>
void GameObject::CollectComponents(std::vector<T*>& out) const {
    for (std::size_t i = FirstComponentToSearch<T>(m_components, transform); i < m_components.size(); ++i)
        if (T* casted = dynamic_cast<T*>(m_components[i].get())) out.push_back(casted);
}

template <typename T>
T* GameObject::GetComponentInChildren(bool includeInactive) const {
    if (!includeInactive && !active) return nullptr;
    if (T* c = GetComponent<T>()) return c;
    if (!transform) return nullptr;
    for (const Transform* child : transform->Children())
        if (child && child->gameObject)
            if (T* c = child->gameObject->GetComponentInChildren<T>(includeInactive)) return c;
    return nullptr;
}

template <typename T>
std::vector<T*> GameObject::GetComponentsInChildren(bool includeInactive) const {
    std::vector<T*> result;
    std::vector<const GameObject*> stack{this};   // explicit stack: pre-order, children kept in order
    while (!stack.empty()) {
        const GameObject* g = stack.back(); stack.pop_back();
        if (!includeInactive && !g->active) continue;
        g->CollectComponents<T>(result);
        if (g->transform) {
            const auto& kids = g->transform->Children();
            for (std::size_t i = kids.size(); i-- > 0;)
                if (kids[i] && kids[i]->gameObject) stack.push_back(kids[i]->gameObject);
        }
    }
    return result;
}

template <typename T>
T* GameObject::GetComponentInParent(bool includeInactive) const {
    for (const GameObject* g = this; g;) {
        if (includeInactive || g->active)
            if (T* c = g->GetComponent<T>()) return c;
        const Transform* p = g->transform ? g->transform->Parent() : nullptr;
        g = p ? p->gameObject : nullptr;
    }
    return nullptr;
}

} // namespace okay
