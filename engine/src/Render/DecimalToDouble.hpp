// Exact decimal-to-double conversion for plain decimal numbers ("12", "-0.5", "1.25e-3", "0.30000000000000004"), the
// value strtod gives in round-to-nearest-even, without strtod for all but a tiny set of inputs. Internal: not installed.
//
// Written for this engine from published descriptions, not from any library's code (CLAUDE.md rule 19a):
//   - Clinger's fast path (W. D. Clinger, "How to read floating point numbers accurately", PLDI 1990): an integer below
//     2^53 and a power of ten up to 10^22 are both exact doubles, so ONE correctly rounded multiplication or division
//     gives the correctly rounded value.
//   - The general case follows the idea of D. Lemire, "Number Parsing at a Gigabyte per Second" (Software: Practice and
//     Experience, 2021), from the paper's description: multiply the decimal significand by a 128-bit approximation of
//     5^q and read the double's bits from the top of the product, and give up when the approximation error could
//     change the rounding. The error analysis below is worked out here for a table rounded DOWN, and is what the
//     code checks; the table (Pow5Table.inc) is generated by scripts/gen_pow5_table.py from exact integers.
//
// The error analysis. A decimal is w * 10^q = w * 5^q * 2^q with w a non-zero 64-bit integer. Shift w left until its top
// bit is set (by l bits). The table gives T (2^127 <= T < 2^128) and s with T <= 5^q * 2^-s < T + 1. Let X be the exact
// real w * 5^q * 2^-s and P = w * T, a 192-bit integer that we compute exactly. Then P <= X < P + w <= P + 2^64, and
// P = X exactly when 0 <= q <= 55 (the table entry is exact). X lies in [2^190, 2^192): its top bit t is 190 or 191, and the
// value is X * 2^(s - l + q), so its leading binary digit has weight 2^e with e = t + s - l + q. The double keeps the bits
// of X from t down to a position p: p = t - 52 for a normal result, higher by (-1022 - e) for a subnormal one; the bit at
// p - 1 is the round bit, the bits below it decide ties. With R the true remainder below p - 1 (R = P mod 2^(p-1) + d,
// 0 <= d < 2^64):
//   - if the bits of P from 64 up to p - 2 are all ones, adding d may carry into the kept bits: we cannot tell, give up;
//   - otherwise the kept bits and the round bit of P are those of X. If the table entry is exact, d = 0 and the remainder
//     is known: round to nearest, ties to even. If not, d > 0 (w > 0 and 5^q * 2^-s - T > 0), so the remainder is never
//     zero: there is no tie, round up exactly when the round bit is set.
// A significand with more than 19 digits is cut to its first 19 (w) and converted twice, as w and as w + 1: the true value
// lies strictly between, so when both give the same double that is the answer (rounding is monotonic); otherwise give up.
// "Give up" returns false; the caller then uses strtod. tests/test_decimal_to_double.cpp checks all of this against strtod
// bit for bit and re-derives every table entry with its own big-integer arithmetic.
