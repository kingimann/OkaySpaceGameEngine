#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.txt from scripts/third_party_notices_data.json.

The notices file lists every third-party library and asset that ships in a release, with the copyright line and
the licence text exactly as the repository already holds it (copied from the licence files named in the data
file; nothing is written from memory). If an item has no licence file, the text says
"licence text missing: owner to supply".

  python3 scripts/gen_third_party_notices.py                 rewrite THIRD_PARTY_NOTICES.txt
  python3 scripts/gen_third_party_notices.py --check         exit 1 if the file is stale or the data is invalid
  python3 scripts/gen_third_party_notices.py --list-files    print the licence files that must ship (one per line)
  python3 scripts/gen_third_party_notices.py --missing       print the items whose licence text is missing
  python3 scripts/gen_third_party_notices.py --stage DIR     copy THIRD_PARTY_NOTICES.txt to DIR and the licence
                                                             files to DIR/Licenses/ (used by build-windows-dist.sh)
"""
import json
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "scripts", "third_party_notices_data.json")
OUT = os.path.join(ROOT, "THIRD_PARTY_NOTICES.txt")
MISSING = "licence text missing: owner to supply"
STATUSES = ("PERMITTED", "NEEDS NOTICE", "UNKNOWN")
RULE = "=" * 78


def load():
    with open(DATA, encoding="utf-8") as f:
        items = json.load(f)["items"]
    seen = set()
    for it in items:
        for k in ("id", "name", "kind", "version", "copyright", "licence", "licence_files", "status", "ships_in"):
            if k not in it:
                raise SystemExit("data error: item %r lacks %r" % (it.get("id"), k))
        if it["id"] in seen:
            raise SystemExit("data error: duplicate id %r" % it["id"])
        seen.add(it["id"])
        if it["status"] not in STATUSES:
            raise SystemExit("data error: %r has status %r" % (it["id"], it["status"]))
        for p in it["licence_files"]:
            if not os.path.isfile(os.path.join(ROOT, p)):
                raise SystemExit("data error: %r names a licence file that is not in the repository: %s" % (it["id"], p))
        if not it["licence_files"] and "no_text_needed" not in it and it["status"] == "PERMITTED":
            raise SystemExit("data error: %r is PERMITTED but has no licence file" % it["id"])
    return items


def read_text(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8", newline="") as f:
        return f.read().replace("\r\n", "\n").rstrip("\n")


def staged_name(rel):
    return rel.replace("/", "__")


def render(items):
    out = []
    out.append("OkaySpace third-party notices")
    out.append(RULE)
    out.append("")
    out.append("OkaySpace includes or ships the third-party software and assets listed below. Each keeps its own")
    out.append("licence. The licence text is copied from the licence file the project holds for it; the same files are")
    out.append("in the Licenses folder next to this file. This file is generated by scripts/gen_third_party_notices.py")
    out.append("from scripts/third_party_notices_data.json. Where a line says \"%s\", the project" % MISSING)
    out.append("does not yet hold that text.")
    out.append("")
    out.append("Contents")
    for i, it in enumerate(items, 1):
        out.append("  %2d. %s [%s]" % (i, it["name"], it["status"]))
    for i, it in enumerate(items, 1):
        out.append("")
        out.append(RULE)
        out.append("%d. %s" % (i, it["name"]))
        out.append(RULE)
        out.append("Kind:       %s" % it["kind"])
        out.append("Version:    %s" % it["version"])
        out.append("Copyright:  %s" % it["copyright"])
        out.append("Licence:    %s" % it["licence"])
        out.append("Status:     %s" % it["status"])
        out.append("Used in:    %s" % it["ships_in"])
        if it.get("note"):
            out.append("Note:       %s" % it["note"])
        out.append("")
        if it["licence_files"]:
            for p in it["licence_files"]:
                out.append("--- licence text, from %s ---" % p)
                out.append(read_text(p))
                out.append("--- end of licence text ---")
        elif "no_text_needed" in it:
            out.append(it["no_text_needed"])
        else:
            out.append(MISSING)
    out.append("")
    return "\n".join(out)


def main(argv):
    items = load()
    if "--list-files" in argv:
        for it in items:
            for p in it["licence_files"]:
                print(p)
        return 0
    if "--missing" in argv:
        for it in items:
            if not it["licence_files"] and "no_text_needed" not in it:
                print("%s [%s]" % (it["name"], it["status"]))
        return 0
    text = render(items)
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8", newline="") as f:
                cur = f.read()
        except OSError:
            print("THIRD_PARTY_NOTICES.txt is missing; run scripts/gen_third_party_notices.py")
            return 1
        if cur != text:
            print("THIRD_PARTY_NOTICES.txt is stale; run scripts/gen_third_party_notices.py and commit it")
            return 1
        print("THIRD_PARTY_NOTICES.txt is up to date (%d items)" % len(items))
        return 0
    if "--stage" in argv:
        dest = argv[argv.index("--stage") + 1]
        os.makedirs(os.path.join(dest, "Licenses"), exist_ok=True)
        shutil.copyfile(OUT, os.path.join(dest, "THIRD_PARTY_NOTICES.txt"))
        for it in items:
            for p in it["licence_files"]:
                shutil.copyfile(os.path.join(ROOT, p), os.path.join(dest, "Licenses", staged_name(p)))
        print("staged THIRD_PARTY_NOTICES.txt and %d licence files in %s" % (sum(len(i["licence_files"]) for i in items), dest))
        return 0
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote THIRD_PARTY_NOTICES.txt (%d items)" % len(items))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
