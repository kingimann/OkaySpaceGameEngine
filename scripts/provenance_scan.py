#!/usr/bin/env python3
"""Provenance scan: a text scan for signs that code or data was copied or ported (docs/status/provenance_audit.md).

Every mode is read only and prints file:line leads, never another project's text:
  python3 scripts/provenance_scan.py markers
      Comments and strings in our own sources that name another project or say "ported from", "based on",
      "adapted from" and so on.
  python3 scripts/provenance_scan.py constants
      Known magic constants of other projects and of published shaders / papers (for example the marching-cubes
      edge table, the FXAA 2 reduce constants, Hable's filmic curve). Each hit names the likely source; a hit is a
      lead to read, not a verdict (many are standard algorithm constants that are fine with a source note).
  python3 scripts/provenance_scan.py tables [--min N]
      Literal number tables of at least N entries (default 64) and whether a source note ("RFC", "ISO", "spec",
      "generated by", "worked out", ...) is written within the 25 lines above. "NO NOTE" rows need one.
  python3 scripts/provenance_scan.py marks
      Other companies' product and brand names inside string literals of shipped code (UI text, defaults). A name
      used to talk to that service, or a platform name, is usually fine; a look-alike or a default is not.
  python3 scripts/provenance_scan.py assets
      Every tracked font, picture, sound, model and data file, and whether docs/status/THIRD_PARTY.md or a
      generator script accounts for its folder. "UNACCOUNTED" rows need a record.
  python3 scripts/provenance_scan.py overlap REFDIR [REFDIR ...] [--min-len N] [--min-run N]
      Compares our own sources with a local checkout of another project (for example a source tree that you
      cloned yourself into a scratch folder). It reports runs of consecutive lines that match after whitespace
      and comments are removed. A match of several lines in a row is a lead, not proof; a clean result is not
      proof of originality. It prints file names and line numbers only, never the other code.
  python3 scripts/provenance_scan.py check
      The guard for findings that were fixed (provenance audit 2026-11-26): exits 1 when one comes back, for
      example a shipped file that states a licence other than ours. Quick; scripts/precheck.sh runs it.

A text scan cannot prove that nothing was copied: a port that renames and reorders passes every mode here.
"""
import os, re, subprocess, sys

ROOTS = ["engine", "shared", "editor", "launcher", "player", "okayui", "okayscript", "browser", "relay", "sandbox",
         "platform", "web", "supabase", "deploy", "steam", "tools", "scripts", "tests", "examples", "cmake"]
SKIP = ("engine/third_party", "tests/wycheproof", "tests/data")
EXT = (".cpp", ".hpp", ".h", ".c", ".inl", ".inc", ".py", ".sh", ".cmake", ".glsl", ".hlsl", ".js", ".mjs", ".ts",
       ".html", ".css", ".lua", ".cs", ".bat", ".ps1", ".sql")
# Files with no extension that are code: the okay-cc / okay-ms standard headers (<vector>, <map>, ...).
EXTLESS_DIRS = ("tools/okaycc/include", "tools/okayms/stdinc")
SHIPPED = ("engine", "shared", "editor", "launcher", "player", "okayui", "okayscript", "browser", "relay", "platform",
           "web", "supabase", "assets", "dist")

PROJECTS = (r"Assimp|meshoptimizer|minimp3|stb_[a-z]+|dr_(?:mp3|flac|wav)|TweetNaCl|libsodium|miniz|lodepng|tinyobj|"
            r"Box2D|PhysX|Bullet Physics|btRigidBody|btCollision\w*|Recast|Detour|Jolt|Havok|Godot|Unreal|miniaudio|FreeType|libjpeg|libpng|zlib|"
            r"Freeverb|mikktspace|QuickJS|Duktape|JerryScript|SpiderMonkey|JavaScriptCore|WebKit|Gecko|Servo|"
            r"litehtml|LuaJIT|PUC-Rio|lvm\.c|lparser\.c|lstrlib\.c|ltable\.c|LLVM|libc\+\+|libstdc\+\+|glibc|musl|"
            r"newlib|TinyCC|chibicc|CoreCLR|Roslyn|ReactOS|Mono\.Cecil|Shadertoy|"
            r"learnopengl|GPU Gems|Numerical Recipes|Hacker'?s Delight|Rakos|Rákos|Quilez|Narkowicz|Hable|"
            r"Jimenez|Hoskins|Gustavson|Lottes|Bourke|Bloyd")
MARK = re.compile(r"ported (from|to)|port of|based on [A-Z]|adapted from|taken from [A-Z]|derived from [A-Z]|"
                  r"translated from|copied from|a la |after (Assimp|stb|SDL|ImGui|minimp3|TweetNaCl)|"
                  r"the way (Assimp|stb|SDL|Godot|Unreal)|\b(" + PROJECTS + r")\b", re.I)

# (regex, likely source). Keep the source short; the audit page says how sure each one is.
CONSTANTS = [
    (r"0x0\s*,\s*0x109\s*,\s*0x203", "marching-cubes edge table (Cory Bloyd's tables on Paul Bourke's page)"),
    (r"dirReduce|rcpDirMin|FXAA_REDUCE", "FXAA 2 / 'FXAA PC console' GLSL (Timothy Lottes, NVIDIA; widely reposted)"),
    (r"A\s*=\s*0\.15\s*,\s*B\s*=\s*0\.50", "Hable / Uncharted 2 filmic curve (John Hable, GDC 2010 and blog)"),
    (r"2\.51\s*\*\s*x\s*\+\s*0\.03", "ACES fit (Krzysztof Narkowicz, blog 2016)"),
    (r"52\.9829189", "interleaved gradient noise (Jorge Jimenez, SIGGRAPH 2014)"),
    (r"1\.384615|3\.230769|0\.2270270?", "9-tap gaussian in 5 linear taps (Daniel Rakos, blog 2010)"),
    (r"12\.9898|78\.233|43758\.5453", "fract(sin(dot)) shader hash (folklore, origin unknown)"),
    (r"0x5f3759df", "fast inverse square root (Quake III Arena, GPL)"),
    (r"0x5bd1e995", "MurmurHash2 multiplier (Austin Appleby, public domain)"),
    (r"0xcc9e2d51|0x1b873593", "MurmurHash3 constants (Austin Appleby, public domain)"),
    (r"0x85ebca6b.*0xc2b2ae35|0xff51afd7ed558ccd", "MurmurHash3 finaliser (Austin Appleby, public domain)"),
    (r"0x9E3779B1u?\b|0x85EBCA77|0xC2B2AE3D|0x27D4EB2F|0x165667B1", "xxHash32 primes (Yann Collet, BSD-2)"),
    (r"0x9908b0df", "Mersenne Twister (ISO C++ [rand.predef] parameters)"),
    (r"151\s*,\s*160\s*,\s*137\s*,\s*91", "Ken Perlin's reference permutation table"),
    (r"0\.3660254|0\.2113248", "simplex noise skew factors (Perlin / Gustavson)"),
    # The CRC polynomials, written with a [ ] class so the duplicate guard does not read this pattern as a CRC table.
    (r"0x04C1[1]DB7|0xEDB8[8]320|0x82F6[3]B78", "CRC polynomial (standard; fine with a note)"),
    (r"Lavf\d|LAME3\.\d", "encoder signature in a data file"),
]

NOTE = re.compile(r"RFC|ISO|IEC|ITU|FIPS|IEEE|ECMA|WHATWG|W3C|Unicode|spec|standard|Table [A-Z0-9]|Annex|"
                  r"generated|generator|derived|computed|worked out|our own|from the|written from|see docs|"
                  r"Bourke|paper|manual|documentation|format description", re.I)
NUM = re.compile(r"-?(0[xX][0-9a-fA-F]+|\d+\.?\d*(?:[eE][-+]?\d+)?)[uUlLfF]*")

BRANDS = re.compile(r"\b(Google|Chrome|Chromium|Edge|Firefox|Safari|Bing|DuckDuckGo|Steam|Steamworks|Valve|Epic Games|"
                    r"Unreal|Unity|Xbox|PlayStation|DualShock|DualSense|Nintendo|Switch Pro|Joy-Con|PlayFab|Photon|"
                    r"Discord|Twitch|YouTube|Facebook|Apple|iCloud|Microsoft|Windows Store|Mixamo|Sketchfab|Roblox|"
                    r"Minecraft|Fortnite|Blender|Maya|3ds Max|Photoshop|Supabase|GitHub)\b")
STRLIT = re.compile(r'"(?:[^"\\\n]|\\.){3,}"')

ASSET_EXT = (".ttf", ".otf", ".woff", ".woff2", ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".tga", ".dds", ".ico",
             ".icns", ".psd", ".hdr", ".exr", ".ktx", ".webp", ".svg", ".wav", ".ogg", ".mp3", ".flac", ".opus",
             ".glb", ".gltf", ".fbx", ".obj", ".mtl", ".blend", ".dae", ".zae", ".3ds", ".lwo", ".lxo", ".mdl", ".md2",
             ".md3", ".md5mesh", ".md5anim", ".ms3d", ".smd", ".bvh", ".ase", ".ply", ".stl", ".off", ".bsp", ".pk3",
             ".ogex", ".okaymesh", ".okaydata", ".mesh", ".zip")


def top():
    return subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()


def tracked():
    t = top()
    return t, subprocess.check_output(["git", "-C", t, "ls-files"], text=True).splitlines()


def files(roots=ROOTS):
    t, out = tracked()
    for f in out:
        code = f.endswith(EXT) or (f.startswith(EXTLESS_DIRS) and "." not in os.path.basename(f))
        if f.split("/")[0] in roots and code and not f.startswith(SKIP):
            yield os.path.join(t, f), f


def lines_of(p):
    try:
        return open(p, errors="replace").read().splitlines()
    except OSError:
        return []


def markers():
    n = 0
    for p, rel in files():
        for i, l in enumerate(lines_of(p), 1):
            if MARK.search(l):
                n += 1; print("%s:%d: %s" % (rel, i, l.strip()[:200]))
    print("# %d marker lines" % n, file=sys.stderr)


def constants():
    pats = [(re.compile(rx, re.I), src) for rx, src in CONSTANTS]
    n = 0
    for p, rel in files():
        if rel == "scripts/provenance_scan.py": continue
        for i, l in enumerate(lines_of(p), 1):
            for rx, src in pats:
                if rx.search(l):
                    n += 1; print("%s:%d: %s" % (rel, i, src)); break
    print("# %d constant hits" % n, file=sys.stderr)


def tables(min_n):
    """Brace-delimited runs of number literals (C, C++, shader strings, JS, Python lists)."""
    n = 0
    for p, rel in files():
        if not rel.endswith((".cpp", ".hpp", ".h", ".c", ".inl", ".inc", ".js", ".py", ".glsl", ".hlsl")): continue
        ls = lines_of(p)
        i = 0
        while i < len(ls):
            if re.search(r"[\[{(=]\s*$|[{\[]\s*-?(0[xX]|\d)", ls[i]):
                count, j = 0, i
                while j < len(ls):
                    body = re.sub(r"//.*|#.*", "", ls[j]) if j > i else ls[i][ls[i].find("{") + 1:] if "{" in ls[i] else ls[i]
                    toks = [x for x in re.split(r"[,\s{}\[\]()]+", body) if x]
                    nums = [x for x in toks if NUM.fullmatch(x)]
                    if j > i and toks and len(nums) < len(toks) * 0.8: break
                    count += len(nums)
                    if re.search(r"[}\]]\s*;?\s*$", ls[j]) and j > i: j += 1; break
                    j += 1
                if count >= min_n:
                    ctx = "\n".join(ls[max(0, i - 25):i + 1])
                    m = NOTE.search(ctx)
                    n += 1
                    print("%s:%d: %d numbers, %s" % (rel, i + 1, count, ("note: '%s'" % m.group(0)) if m else "NO NOTE"))
                i = max(j, i + 1)
            else:
                i += 1
    print("# %d tables of %d+ numbers" % (n, min_n), file=sys.stderr)


def marks():
    n = 0
    for p, rel in files(SHIPPED):
        if not rel.endswith((".cpp", ".hpp", ".h", ".c", ".inl", ".inc", ".js", ".html", ".ts")): continue
        for i, l in enumerate(lines_of(p), 1):
            s = l.strip()
            if s.startswith(("//", "*", "/*", "#include")): continue
            for lit in STRLIT.findall(l):
                m = BRANDS.search(lit)
                if m:
                    n += 1; print("%s:%d: %s: %s" % (rel, i, m.group(1), lit[:120])); break
    print("# %d string literals naming another brand" % n, file=sys.stderr)


def assets():
    t, out = tracked()
    tp = open(os.path.join(t, "docs/status/THIRD_PARTY.md"), errors="replace").read()
    gens = [f for f in out if re.search(r"(^|/)(gen_|make_|record_)[^/]*\.(py|cpp|sh)$|/gen_fixtures\.py$", f)]
    gen_text = {g: open(os.path.join(t, g), errors="replace").read() for g in gens}
    rows = {}
    for f in out:
        if not f.lower().endswith(ASSET_EXT): continue
        d = os.path.dirname(f)
        rows.setdefault(d, []).append(f)
    for d in sorted(rows):
        fs = rows[d]
        by = []
        if d in tp or any(os.path.basename(f) in tp for f in fs): by.append("THIRD_PARTY.md")
        for g, txt in gen_text.items():
            # The generator names the folder, sits in it, or names one of its files in full (with the extension).
            if d in txt or os.path.dirname(g) == d or any(os.path.basename(f) in txt for f in fs):
                by.append(g)
        if os.path.exists(os.path.join(t, d, "README.md")): by.append(d + "/README.md")
        state = ", ".join(sorted(set(by))[:3]) if by else "UNACCOUNTED"
        print("%-48s %4d files  %s" % (d, len(fs), state))


# Fixed findings that must not come back: (id, what went wrong, test(top) -> list of "file:line" problems).
def _grep(t, rel, rx):
    try: ls = open(os.path.join(t, rel), errors="replace").read().splitlines()
    except OSError: return ["%s: missing" % rel]
    return ["%s:%d" % (rel, i) for i, l in enumerate(ls, 1) if re.search(rx, l)]


def _licence_statement(t):
    """A4: every Windows program's version information names our licence (LICENSE), not another one."""
    rel = "cmake/okay_version.rc.in"
    bad = _grep(t, rel, r"LegalCopyright.*(MIT|GPL|BSD|Apache|zlib)")
    if not _grep(t, rel, r"LegalCopyright.*All rights reserved\. See LICENSE\."): bad.append(rel + ": LegalCopyright does not say 'All rights reserved. See LICENSE.'")
    return bad


# A10: published shader constants keep a one-line source note (on the line or within the 3 lines above).
A10_PLACES = [
    ("engine/src/Render/GLRendererShaders.cpp", r"2\.51\*x|A = 0\.15|52\.9829189|\* 0\.227027"),
    ("engine/include/okay/Render/D3DPostHLSL.hpp", r"A = 0\.15|\* 0\.227027"),
    ("engine/include/okay/Render/D3D11Hlsl.hpp", r"2\.51\*x|52\.9829189"),
    ("engine/include/okay/Render/DofMath.hpp", r"\* 0\.227027"),
    ("engine/include/okay/Render/SsaoMath.hpp", r"OKAY_SSAO_BLUR_W0 0\.227027"),
    ("engine/include/okay/Render/Atmosphere.hpp", r"2\.51f \* x|A = 0\.15f"),
]
A10_NOTE = re.compile(r"[Ss]ource|derived in|Narkowicz|Hable|Jimenez|binomial")


def _source_notes(t):
    bad = []
    for rel, rx in A10_PLACES:
        try: ls = open(os.path.join(t, rel), errors="replace").read().splitlines()
        except OSError: bad.append(rel + ": missing"); continue
        for i, l in enumerate(ls):
            if re.search(rx, l) and not any(A10_NOTE.search(x) for x in ls[max(0, i - 3):i + 1]):
                bad.append("%s:%d" % (rel, i + 1))
    return bad


def _simplex(t):
    """A2: simplex noise is our own structure and numbers (no reference-code skew literals, corner cascade or scales)."""
    rel = "engine/include/okay/Math/Noise.hpp"
    return _grep(t, rel, r"0\.3660254|0\.2113248|x0 >= y0|70\.0f \* n|32\.0f \* n|0\.6f - x")


def _notices(t):
    """A5-A7: one notice file names every runtime, library and font we ship, and every package carries it."""
    bad = []
    rel = "dist/THIRD_PARTY_NOTICES.txt"
    try: txt = open(os.path.join(t, rel), errors="replace").read()
    except OSError: return [rel + ": missing"]
    for name in ("GCC Runtime Library Exception", "winpthreads", "libsodium", "SDL2", "Dear ImGui", "steam_api64.dll",
                 "Emscripten", "musl", "Roboto", "JetBrains Mono", "DejaVu", "Apache License"):
        if name not in txt: bad.append("%s: does not name %s" % (rel, name))
    if not os.path.isfile(os.path.join(t, "assets/fonts/Roboto-LICENSE.txt")): bad.append("assets/fonts/Roboto-LICENSE.txt: missing")
    for shipper in ("scripts/build-windows-dist.sh", "scripts/okayspace-installer.nsi", "editor/BuildGame.cpp", "scripts/web_package.py"):
        if not _grep(t, shipper, r"THIRD_PARTY_NOTICES\.txt"): bad.append("%s: does not ship THIRD_PARTY_NOTICES.txt" % shipper)
    return bad


def _browser_words(t):
    """A8: the address bar's placeholder uses neutral words, not a look-alike of another browser's."""
    return _grep(t, "engine/src/Browser/Profile.cpp", r'"Search Google or type')


def _ui_brands(t):
    """A9: UI text describes features in plain words, not by another game or a trademark ("Minecraft-style",
    "ACES" as a menu entry). Comments may still name what a feature resembles. The old GameObject > UI menu record
    (editor/UIMenuModel.hpp LegacyItems, never shown) keeps the old labels as history."""
    bad = []
    for p, rel in files(("editor", "engine", "shared", "player", "okayui", "launcher", "browser")):
        if not rel.endswith((".cpp", ".hpp", ".h", ".inl")) or rel == "editor/UIMenuModel.hpp": continue
        for i, l in enumerate(lines_of(p), 1):
            if l.strip().startswith(("//", "*", "/*")): continue
            for lit in STRLIT.findall(l):
                if re.search(r"Minecraft", lit): bad.append("%s:%d" % (rel, i)); break
    bad += _grep(t, "shared/EditorPanelModels.hpp", r'kTonemapNames.*"ACES"')
    return bad


GUARDS = [
    ("A4", "shipped version information states a licence other than ours", _licence_statement),
    ("A2", "simplex noise follows the reference code again", _simplex),
    ("A5-A7", "a package ships without the third-party notices", _notices),
    ("A8", "the browser placeholder copies another browser's wording", _browser_words),
    ("A9", "UI text names another game or uses a trademark as a feature name", _ui_brands),
    ("A10", "a published shader constant has no source note near it", _source_notes),
]


def check():
    t = top()
    n = 0
    for gid, what, fn in GUARDS:
        for hit in fn(t):
            n += 1; print("%s: %s: %s" % (hit, gid, what))
    print("# provenance check: %d problem(s) in %d guards" % (n, len(GUARDS)), file=sys.stderr)
    return 1 if n else 0


def norm(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out = []
    for i, l in enumerate(text.splitlines(), 1):
        l = re.sub(r"//.*$", "", l)
        l = re.sub(r"\s+", "", l)
        if l.startswith("#"): l = ""          # includes, defines and pragmas are not evidence
        out.append((i, l))
    return out


def overlap(refs, min_len, min_run):
    index = {}
    for ref in refs:
        for d, _, fs in os.walk(ref):
            for f in fs:
                if f.endswith((".cpp", ".h", ".hpp", ".c", ".inl", ".cc")):
                    p = os.path.join(d, f)
                    try: t = open(p, errors="replace").read()
                    except OSError: continue
                    for i, l in norm(t):
                        if len(l) >= min_len: index.setdefault(l, set()).add(os.path.relpath(p, ref))
    for p, rel in files():
        if not rel.endswith((".cpp", ".hpp", ".h", ".c", ".inl")) and "." in os.path.basename(rel): continue
        try: t = open(p, errors="replace").read()
        except OSError: continue
        run, start, hit = 0, 0, set()
        for i, l in norm(t):
            if len(l) >= min_len and l in index:
                if run == 0: start = i; hit = set()
                run += 1; hit |= index[l]
            elif l == "" or len(l) < min_len:
                continue          # short or blank lines do not break a run
            else:
                if run >= min_run: print("%s:%d-%d: %d matching lines, in %s" % (rel, start, i - 1, run, ", ".join(sorted(hit)[:3])))
                run = 0
        if run >= min_run: print("%s:%d-: %d matching lines, in %s" % (rel, start, run, ", ".join(sorted(hit)[:3])))


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:1] == ["markers"]: markers()
    elif a[:1] == ["constants"]: constants()
    elif a[:1] == ["tables"]: tables(int(a[2]) if a[1:2] == ["--min"] else 64)
    elif a[:1] == ["marks"]: marks()
    elif a[:1] == ["assets"]: assets()
    elif a[:1] == ["check"]: sys.exit(check())
    elif a[:1] == ["overlap"] and len(a) > 1:
        mn, mr, refs, k = 12, 3, [], 1
        while k < len(a):
            if a[k] == "--min-len": mn = int(a[k + 1]); k += 2
            elif a[k] == "--min-run": mr = int(a[k + 1]); k += 2
            else: refs.append(a[k]); k += 1
        overlap(refs, mn, mr)
    else: print(__doc__); sys.exit(2)
