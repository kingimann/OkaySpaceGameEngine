namespace detail {
/// Moves whenever an `active` flag changes value or a parent link changes, anywhere in the process.
/// GameObject::ActiveInHierarchy() keeps its answer for as long as this number stays the same.
inline std::atomic<std::uint64_t> g_activeEpoch{1};
/// How many objects ActiveInHierarchy() had to look at to compute an answer (cache hits cost nothing).
inline std::atomic<std::uint64_t> g_activeWalkSteps{0};
} // namespace detail

/// The type of GameObject::active: a bool that notes every change of its value, so
/// GameObject::ActiveInHierarchy() can remember its answer instead of walking the parents again for
/// every component every frame. It reads and assigns like a bool (`if (go->active)`, `go->active = false`);
/// assigning the value it already holds changes nothing.
class ActiveFlag {
public:
    explicit constexpr ActiveFlag(bool on = true) : m_on(on) {}
    ActiveFlag(const ActiveFlag& o) : m_on(o.m_on) {}
    ActiveFlag& operator=(const ActiveFlag& o) { Set(o.m_on); return *this; }
    ActiveFlag& operator=(bool on) { Set(on); return *this; }
    operator bool() const { return m_on; }
private:
    void Set(bool on) {
        if (on == m_on) return;
        m_on = on;
        detail::g_activeEpoch.fetch_add(1, std::memory_order_relaxed);
    }
    bool m_on;
};

/// Process-wide, data-driven rules for AddComponent: components a type needs next to
/// it (RequireComponent) and types that may appear once per object
/// (DisallowMultipleComponent). Register once at startup (before scenes load);
/// the rules are then applied to every AddComponent<T> call, the editor's
/// Add Component menu and the scene loader included. Exact-type match on T.
class ComponentRules {
public:
    struct Requirement {
        std::type_index type;
        bool       (*has)(const GameObject&);
        void       (*add)(GameObject&);
    };
    static void AddRequirement(std::type_index owner, Requirement req);
    static void SetUnique(std::type_index owner);
    /// True once any rule exists (lets AddComponent skip all of this when none do).
    static bool Any();
    static bool IsUnique(std::type_index owner);
    /// Copy of the requirements of `owner` (empty if none).
    static std::vector<Requirement> RequirementsOf(std::type_index owner);
    /// Remove every rule (tests).
    static void Clear();
};

/// A named container of Components living in a Scene — the engine's primary
/// unit of composition, modeled directly on GameObject.
class GameObject {
public:
    std::string name;
    /// This object's own on/off flag ("activeSelf"). Inactive GameObjects are skipped
    /// by Update, Render and physics, and so are their children: what the engine
    /// tests is ActiveInHierarchy(), which also looks at every parent. (An ActiveFlag: use it as a bool.)
    ActiveFlag active{true};
    /// Scene bookkeeping: the `active` value last reported to OnEnable/OnDisable
    /// (-1 = not seen yet, so the first frame never fires either).
    signed char activeSeen = -1;
    /// Optional tag for lookups (see Scene::FindWithTag). Behaves as a std::string.
    TagString tag;
    /// Set the tag if Tags::Accepts it (valid name; in the list when Tags::Strict()).
    /// "" clears it. Returns false and leaves the tag alone when refused.
    bool SetTag(const std::string& t) { if (!Tags::Accepts(t)) return false; tag = t; return true; }
    /// True when this object carries exactly `t` (case matters). The empty tag is never matched.
    bool CompareTag(const std::string& t) const { return !t.empty() && tag == t; }
    /// Runtime-only object (generated by a component, e.g. CraftingMenu's buttons):
    /// never written by the scene serializer, so saving and loading can't duplicate it.
    bool transient = false;
    /// Records of this object that the scene file had and this build does not know (a component or a field a
    /// newer build wrote), each the whole line after its indentation, e.g. `newthing 1 2 "x"`. They are written
    /// back as they were, so opening a file with an older build and saving it does not lose them. Copies
    /// (Instantiate, Duplicate, an undo snapshot) carry them, as they go through the same text. Data only.
    std::vector<std::string> unknownRecords;
    /// If this object was instantiated from a .okayprefab file, the path to that
    /// file (empty otherwise). Links the instance to its source prefab so the
    /// editor can Apply changes back, Revert to the saved prefab, or reload every
    /// instance when the prefab file changes. Only the instance ROOT carries it.
    std::string prefabSource;
    /// One field of a prefab instance that differs from its source prefab (see
    /// docs/prefabs.md). `object` is the depth-first index of the object inside the
    /// prefab (0 = the instance root); `line` is the whole serialized record, e.g.
    /// `sprite 64 1 1 1 1 1 1`. Re-applying the prefab keeps these. Data only.
    struct PrefabOverride {
        int object = 0;
        std::string line;
    };
    /// The overrides this instance remembers (instance ROOT only, with prefabSource).
    std::vector<PrefabOverride> prefabOverrides;
    /// Render/physics layer (0-31). A camera's cullingMask selects which layers it
    /// draws (bit 1<<layer); also used by the physics collision matrix.
    int layer = 0;
    /// Put this object on `newLayer`, and with `includeChildren` every object below it too.
    /// Returns false and changes nothing when the layer is not 0-31.
    bool SetLayer(int newLayer, bool includeChildren = false);
    /// The names of the objects from the top of the hierarchy down to this one, joined with
    /// '/': "Arm/Hand/Finger". Scene::FindByPath reads this form back.
    std::string Path() const;
    /// Marked non-moving. A hint for tools/builds; objects flagged
    /// static are not expected to move at runtime.
    bool isStatic = false;

    /// Editor-only: locked objects can't be click-selected or dragged in the Scene
    /// view (pick them via the Hierarchy). Protects backdrops/ground from stray
    /// clicks while arranging things on top. No runtime effect; persisted.
    bool editorLocked = false;

    /// The name of the scene this object was MERGED in from (empty = it belongs to
    /// the main/host scene). Set when combining scenes so the editor's Hierarchy can
    /// show where each merged scene starts and ends. Persisted with the scene.
    std::string sourceScene;

    /// Per-object UI layering override. 0 = use the widget's default type layer
    /// (the historic per-type pass order); any non-zero value places this widget in
    /// the single UI draw pass by this key instead (higher = drawn later / on top),
    /// letting non-nested widgets of different types be layered freely. Ignored by
    /// non-UI objects. Hierarchy pre-order breaks ties.
    int uiDrawOrder = 0;

    /// First-person viewmodel flag. A camera that is told to IGNORE this object's
    /// owner (the local player, via Camera::ignoreObject) normally skips the whole
    /// player subtree — that's how you don't see your own body in first person.
    /// Objects flagged here are the EXCEPTION: they render for the owner's own camera
    /// even though they live inside the ignored subtree — exactly the Minecraft/Unturned
    /// "viewmodel": the body is hidden from the owner only, while the arm (this flag)
    /// stays visible to the owner. Other cameras (remote players) don't ignore this
    /// player at all, so they see the full body regardless of this flag.
    bool firstPersonViewmodel = false;

    /// A copy that exists only for the camera hiding this object's owner (the
    /// raised first-person arm). Colour passes draw it only for that camera.
    /// Shadow passes never draw it, so the copy cannot change another view.
    /// Not saved. The real body is a different object and is left alone.
    bool firstPersonOnly = false;

    /// A camera that ignores this object also skips this one. The real held
    /// prop uses it while the owner's viewmodel shows its own copy. Not saved.
    GameObject* ownerCameraSkip = nullptr;

    /// Every GameObject has a Transform from birth.
    Transform* transform = nullptr;

    /// True when this object and every parent above it are active. A child of an
    /// inactive parent does not update, render or simulate even if its own `active`
    /// is true. The answer is kept until some `active` flag or parent link changes anywhere
    /// (then it is worked out again, sharing the work with the objects above it), so a frame over a
    /// long chain costs a few reads per component, not a walk to the top of the hierarchy.
    /// Reading it from several threads is safe while nothing is being changed.
    bool ActiveInHierarchy() const {
        const std::uint64_t epoch = detail::g_activeEpoch.load(std::memory_order_relaxed);
        const std::uint64_t seen = m_activeCache.load(std::memory_order_relaxed);
        if ((seen >> 1) == epoch) return (seen & 1u) != 0;
        return ComputeActiveInHierarchy(epoch);
    }
    /// Diagnostic: how many objects ActiveInHierarchy() has had to examine since the process
    /// started. An answer that comes from the cache adds nothing; tests use the difference to show
    /// that a frame does linear work.
    static std::uint64_t ActiveWalkSteps() { return detail::g_activeWalkSteps.load(std::memory_order_relaxed); }

    /// Attach a new component of type T, forwarding constructor arguments.
    template <typename T, typename... Args>
    T* AddComponent(Args&&... args);

    /// The first attached component of type T, or a new one made with `args` when there is none (the way
    /// to say "I need a Rigidbody here" without checking first). With a RequireComponent or
    /// DisallowMultipleComponent rule registered for T the rule applies to the one that is added.
    template <typename T, typename... Args>
    T* GetOrAddComponent(Args&&... args);

    /// Return the first attached component of type T, or nullptr.
    template <typename T>
    T* GetComponent() const;

    /// Return every attached component assignable to T.
    template <typename T>
    std::vector<T*> GetComponents() const;

    /// The first component of type T on this object or, failing that, any object below it
    /// (depth first, children in sibling order). Inactive objects are skipped, with
    /// their children, unless `includeInactive`.
    template <typename T>
    T* GetComponentInChildren(bool includeInactive = false) const;
    /// Every component of type T on this object and the objects below it (depth first).
    template <typename T>
    std::vector<T*> GetComponentsInChildren(bool includeInactive = false) const;
    /// The first component of type T on this object or one of its parents, nearest first.
    template <typename T>
    T* GetComponentInParent(bool includeInactive = false) const;
    /// Every component of type T on this object and each parent above it: the object itself first, then
    /// its parent, and so on up; an object's own components in stored order. An inactive object is
    /// skipped (its parents are still looked at) unless `includeInactive`.
    template <typename T>
    std::vector<T*> GetComponentsInParent(bool includeInactive = false) const;

    /// Call `fn(GameObject&)` for the objects below this one: parents before children, siblings in their
    /// order (this object first too with `includeSelf`). When `fn` returns a bool, returning false stops the
    /// walk at once; a function that returns nothing visits everything. An object whose own `active` is off
    /// is skipped with everything below it unless `includeInactive` (the default visits every object); the rule
    /// covers this object too, so with `includeInactive` false a switched-off start visits nothing. Returns
    /// true when the whole walk ran and false when `fn` stopped it. Objects an `fn` call asks the scene to destroy are
    /// still visited (they go at the end of the frame); a child it adds to the object it was just called for
    /// is visited too. Uses an explicit stack, so a very deep hierarchy is fine.
    template <typename Fn>
    bool ForEachDescendant(Fn&& fn, bool includeInactive = true, bool includeSelf = false) const;

    /// True when this object or anything below it has a component that was told OnEnable and not yet
    /// OnDisable (see HasLiveComponent for one object). A pool uses it to tell when a released object, its
    /// children included, has been switched off for real.
    bool HasLiveComponentInHierarchy() const;

    /// Append every component assignable to T to `out` (no per-object allocation;
    /// used by Scene::FindObjectsOfType to avoid a temporary vector per object).
    template <typename T>
    void CollectComponents(std::vector<T*>& out) const;

    /// Iterate the attached components in their stored order.
    /// The reference is into this object's storage: do not AddComponent or
    /// RemoveComponent while a range-for is walking it. CopyComponentPointers
    /// is the list to walk when a callback might add components.
    const std::vector<std::unique_ptr<Component>>& Components() const { return m_components; }
    /// Pointers to the components in stored order, copied out of the vector.
    /// Adding a component can reallocate that vector; these pointers still
    /// refer to the component objects (they are individually heap-allocated).
    void CopyComponentPointers(std::vector<Component*>& out) const {
        out.clear();
        out.reserve(m_components.size());
        for (const auto& c : m_components) out.push_back(c.get());
    }
    /// Free every component except the Transform (used when the scene destroys
    /// the object: the shell stays alive so stale pointers never dangle). The
    /// scene records the freed addresses in its removal watches first, so code
    /// holding raw pointers across this (a StartComponent's watch) skips them.
    void StripToTransform();
    /// True if some component has been told OnEnable and not yet OnDisable (it is
    /// "live"). An object switched off this frame still reads true until the Scene
    /// delivers OnDisable at the start of the next one.
    bool HasLiveComponent() const {
        for (const auto& c : m_components) if (c->m_live) return true;
        return false;
    }
    /// True once the scene destroyed this object (it's only a Transform shell now).
    bool IsDestroyed() const { return m_destroyed; }

    /// True if `other` is this object or any ancestor of it — used by cameras to skip
    /// a whole subtree (e.g. hiding the local player's body, rig parts included, from
    /// the first-person view without affecting other cameras).
    bool IsSelfOrDescendantOf(const GameObject* other) const;

    /// True when a camera whose ignore object is `camIgnore` should skip this
    /// object. A first-person-only copy is drawn solely for the camera that is
    /// hiding its owner. Any other object in that owner's subtree is skipped
    /// unless it is a viewmodel that camera is meant to see.
    bool HiddenFromCamera(const GameObject* camIgnore) const {
        if (firstPersonOnly)
            return !camIgnore || !IsSelfOrDescendantOf(camIgnore);
        if (ownerCameraSkip && camIgnore == ownerCameraSkip) return true;
        return camIgnore && IsSelfOrDescendantOf(camIgnore) && !firstPersonViewmodel;
    }

    /// Move `component` by `delta` positions within the stored order. Transform
    /// is pinned to index 0: the valid target range is [1, size-1], so neither the
    /// Transform itself nor any other component can be moved to index 0. Out-of-range
    /// moves or an unknown component are no-ops.
    void MoveComponent(Component* component, int delta);
    /// Arrange the components: the ones in `first` that belong to this object come right after the
    /// Transform, in that order; everything else follows in the order it already had. A null, the
    /// Transform, a component of another object and a repeat are skipped. Returns true when the order
    /// changed. Calling it with at least one component of this object (or a MoveComponent that moved)
    /// marks the order as arranged on purpose, so the scene file keeps it (see HasCustomComponentOrder).
    bool ReorderComponents(const std::vector<Component*>& first);
    /// True once the component order was arranged on purpose (MoveComponent, ReorderComponents, or
    /// loaded from a `comporder` record). The scene serializer writes the order of such an object, and
    /// only of such an object, so an object nobody arranged saves exactly as before.
    bool HasCustomComponentOrder() const { return m_customOrder; }

    /// If another component on this object needs `component` (RequireComponent),
    /// that dependent; else nullptr. Lets an editor refuse to remove it. RemoveComponent
    /// itself does not check, so scene teardown and scripts keep working.
    Component* RequiredBy(const Component* component) const;

    /// Remove a specific component (Transform cannot be removed). Returns true
    /// if it was found and removed.
    bool RemoveComponent(Component* component);
    /// Remove the first component of type T. Returns true if one was removed.
    template <typename T>
    bool RemoveComponent() {
        for (const auto& c : m_components)
            if (T* casted = dynamic_cast<T*>(c.get())) return RemoveComponent(casted);
        return false;
    }

    Scene* scene() const { return m_scene; }

    /// A number unique to this object for the whole run (never reused), so scripts
    /// can hold a reference that safely turns into "destroyed" instead of dangling.
    std::uint64_t InstanceId() const { return m_instanceId; }
    /// A persistent id (32 lowercase hex characters) that, unlike InstanceId, is saved
    /// with the scene: it is the same after a save and load, and references between
    /// objects can use it (Scene::FindByGuid). Every new object gets a fresh one;
    /// Instantiate / paste / merge give the copy its own. A scene file with no guid
    /// record (older files) gets fresh ids on load.
    const std::string& Guid() const { return m_guid; }
    /// Replace the id. Ignored (returns false) unless `guid` is 1 to 64 characters
    /// of [0-9a-f-]. Used by the loader; callers keep ids unique themselves.
    bool SetGuid(const std::string& guid);
    /// The live object with this id, or nullptr once it's gone (or destroyed).
    static GameObject* FromInstanceId(std::uint64_t id);

    ~GameObject();
    GameObject(const GameObject&) = delete;
    GameObject& operator=(const GameObject&) = delete;

private:
    friend class Scene;
    explicit GameObject(Scene* scene, std::string name);
    std::uint64_t m_instanceId = 0;
    std::string m_guid;

    /// Routes a freshly added component to the Scene's lifecycle queue.
    /// Defined in GameObject.cpp where the full Scene type is visible.
    void NotifyComponentAdded(Component* component);
    /// Adds the components `owner` requires that are missing (guards against cycles).
    void ApplyRequirements(std::type_index owner);

    /// The cache behind ActiveInHierarchy(): (epoch << 1) | answer. Valid while its epoch is current.
    bool ComputeActiveInHierarchy(std::uint64_t epoch) const;
    mutable std::atomic<std::uint64_t> m_activeCache{0};

    Scene* m_scene = nullptr;
    std::vector<std::unique_ptr<Component>> m_components;
    bool m_destroyed = false;
    bool m_customOrder = false;
};

// ---- Template implementations -----------------------------------------

template <typename T, typename... Args>
T* GameObject::AddComponent(Args&&... args) {
    static_assert(std::is_base_of<Component, T>::value,
                  "T must derive from okay::Component");
    // An object has one Transform from birth: asking for another returns it.
    if constexpr (std::is_same<T, Transform>::value) { if (transform) return transform; }
    if (ComponentRules::Any()) {
        // DisallowMultipleComponent: a second one is not made; the existing one comes back.
        if (ComponentRules::IsUnique(typeid(T)))
            if (T* existing = GetComponent<T>()) return existing;
        ApplyRequirements(typeid(T));   // RequireComponent: the needed siblings first
    }
    auto owned = std::make_unique<T>(std::forward<Args>(args)...);
    T* ptr = owned.get();
    ptr->gameObject = this;
    ptr->transform  = transform ? transform : dynamic_cast<Transform*>(ptr);
    m_components.push_back(std::move(owned));
    NotifyComponentAdded(ptr); // declared in Scene.hpp, defined in Scene.cpp
    return ptr;
}

// Component lookups run every frame all over the engine. Every object's first
// component is its Transform, so a lookup for a type that can't be a Transform
// starts after it (a bone object with nothing but a Transform then costs no
// dynamic_cast at all), and an exact type match skips the dynamic_cast walk.
template <typename T>
inline std::size_t FirstComponentToSearch(const std::vector<std::unique_ptr<Component>>& cs, const Transform* t) {
    if constexpr (std::is_base_of<T, Transform>::value) return 0;
    else return (!cs.empty() && cs[0].get() == static_cast<const Component*>(t)) ? 1 : 0;
}

template <typename T>
T* GameObject::GetComponent() const {
    for (std::size_t i = FirstComponentToSearch<T>(m_components, transform); i < m_components.size(); ++i) {
        Component* c = m_components[i].get();
        if (typeid(*c) == typeid(T)) return static_cast<T*>(c);
        if constexpr (!std::is_final<T>::value)   // a final type has no subclasses to find
            if (T* casted = dynamic_cast<T*>(c)) return casted;
    }
    return nullptr;
}

template <typename T>
std::vector<T*> GameObject::GetComponents() const {
    std::vector<T*> result;
    for (std::size_t i = FirstComponentToSearch<T>(m_components, transform); i < m_components.size(); ++i)
        if (T* casted = dynamic_cast<T*>(m_components[i].get())) result.push_back(casted);
    return result;
}

template <typename T>
void GameObject::CollectComponents(std::vector<T*>& out) const {
    for (std::size_t i = FirstComponentToSearch<T>(m_components, transform); i < m_components.size(); ++i)
        if (T* casted = dynamic_cast<T*>(m_components[i].get())) out.push_back(casted);
}

/// Declare that every `T` needs a `Req` on its object: AddComponent<T> adds one first
/// if it is missing. Call once at startup.
template <typename T, typename Req>
void RequireComponent() {
    static_assert(std::is_base_of<Component, T>::value && std::is_base_of<Component, Req>::value,
                  "both must derive from okay::Component");
    ComponentRules::AddRequirement(typeid(T), {
        std::type_index(typeid(Req)),
        [](const GameObject& g) { return g.GetComponent<Req>() != nullptr; },
        [](GameObject& g) { g.AddComponent<Req>(); }});
}
/// Declare that an object holds at most one `T`: a second AddComponent<T> returns the
/// existing one. Call once at startup.
template <typename T>
void DisallowMultipleComponent() {
    static_assert(std::is_base_of<Component, T>::value, "T must derive from okay::Component");
    ComponentRules::SetUnique(typeid(T));
}

template <typename T, typename... Args>
T* GameObject::GetOrAddComponent(Args&&... args) {
    if (T* existing = GetComponent<T>()) return existing;
    return AddComponent<T>(std::forward<Args>(args)...);
}

template <typename Fn>
bool GameObject::ForEachDescendant(Fn&& fn, bool includeInactive, bool includeSelf) const {
    std::vector<GameObject*> stack;   // explicit stack: pre-order, children kept in order, no recursion
    auto pushChildren = [&stack](const GameObject* g) {
        if (!g->transform) return;
        const auto& kids = g->transform->Children();
        for (std::size_t i = kids.size(); i-- > 0;)
            if (kids[i] && kids[i]->gameObject) stack.push_back(kids[i]->gameObject);
    };
    auto visit = [&fn](GameObject* g) -> bool {
        if constexpr (std::is_same<decltype(fn(*g)), bool>::value) return fn(*g);
        else { fn(*g); return true; }
    };
    if (!includeInactive && !active) return true;   // switched off: it and everything below it are skipped
    if (includeSelf && !visit(const_cast<GameObject*>(this))) return false;
    pushChildren(this);
    while (!stack.empty()) {
        GameObject* g = stack.back(); stack.pop_back();
        if (!includeInactive && !g->active) continue;
        if (!visit(g)) return false;
        pushChildren(g);
    }
    return true;
}

template <typename T>
T* GameObject::GetComponentInChildren(bool includeInactive) const {
    std::vector<const GameObject*> stack{this};   // explicit stack: depth first, children in sibling order, no recursion
    while (!stack.empty()) {
        const GameObject* g = stack.back(); stack.pop_back();
        if (!includeInactive && !g->active) continue;
        if (T* c = g->GetComponent<T>()) return c;
        if (g->transform) {
            const auto& kids = g->transform->Children();
            for (std::size_t i = kids.size(); i-- > 0;)
                if (kids[i] && kids[i]->gameObject) stack.push_back(kids[i]->gameObject);
        }
    }
    return nullptr;
}

template <typename T>
std::vector<T*> GameObject::GetComponentsInChildren(bool includeInactive) const {
    std::vector<T*> result;
    std::vector<const GameObject*> stack{this};   // explicit stack: pre-order, children kept in order
    while (!stack.empty()) {
        const GameObject* g = stack.back(); stack.pop_back();
        if (!includeInactive && !g->active) continue;
        g->CollectComponents<T>(result);
        if (g->transform) {
            const auto& kids = g->transform->Children();
            for (std::size_t i = kids.size(); i-- > 0;)
                if (kids[i] && kids[i]->gameObject) stack.push_back(kids[i]->gameObject);
        }
    }
    return result;
}

template <typename T>
T* GameObject::GetComponentInParent(bool includeInactive) const {
    for (const GameObject* g = this; g;) {
        if (includeInactive || g->active)
            if (T* c = g->GetComponent<T>()) return c;
        const Transform* p = g->transform ? g->transform->Parent() : nullptr;
        g = p ? p->gameObject : nullptr;
    }
    return nullptr;
}

template <typename T>
std::vector<T*> GameObject::GetComponentsInParent(bool includeInactive) const {
    std::vector<T*> result;
    for (const GameObject* g = this; g;) {
        if (includeInactive || g->active) g->CollectComponents<T>(result);
        const Transform* p = g->transform ? g->transform->Parent() : nullptr;
        g = p ? p->gameObject : nullptr;
    }
    return result;
}

