#!/usr/bin/env python3
"""Writes engine/src/Render/Pow5Table.inc: 128-bit approximations of 5^q for the exact decimal-to-double conversion in
engine/src/Render/DecimalToDouble.hpp (docs/content/model_readers.md (FBX part), "Exact ASCII numbers").

Written for this engine from the definition, with Python's exact integers; no table from elsewhere was copied.

For each q in [-342, 308] the table holds T(q), a 128-bit integer with its top bit set (2^127 <= T < 2^128), and s(q) such
that T(q) * 2^s(q) is 5^q rounded DOWN to 128 significant bits:
  q >= 0: 5^q has b bits; T = 5^q shifted to 128 bits (exact when b <= 128, that is q <= 55; else the low bits are cut
          off), s = b - 128.
  q <  0: d = 5^-q has b bits; T = floor(2^(127 + b) / d), which lies in (2^127, 2^128) because d is odd and not a power
          of two; s = -(127 + b).
So T <= 5^q * 2^-s < T + 1 always, with equality exactly for 0 <= q <= 55. The range: below 10^-342 any decimal with at
most 20 significant digits is under half the smallest subnormal double (it rounds to zero); above 10^308 every non-zero
decimal is beyond the largest double (it rounds to infinity).

  python3 scripts/gen_pow5_table.py            write the file
  python3 scripts/gen_pow5_table.py --check    exit 1 if the committed file differs from what this script writes
"""
import os
import sys

QMIN, QMAX = -342, 308
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "src", "Render", "Pow5Table.inc")


def entry(q):
    if q >= 0:
        v = 5 ** q
        b = v.bit_length()
        t = v << (128 - b) if b <= 128 else v >> (b - 128)
        s = b - 128
        exact = b <= 128
    else:
        d = 5 ** (-q)
        b = d.bit_length()
        t = (1 << (127 + b)) // d
        s = -(127 + b)
        exact = False
    assert (1 << 127) <= t < (1 << 128), q
    # T * 2^s <= 5^q < (T + 1) * 2^s, checked with integers only (both sides times 2^-s, or times 5^-q)
    if q >= 0:
        lhs, mid, rhs = (t << s) if s >= 0 else t, (5 ** q) if s >= 0 else (5 ** q) << (-s), ((t + 1) << s) if s >= 0 else t + 1
    else:
        d = 5 ** (-q)
        lhs, mid, rhs = t * d, 1 << (-s), (t + 1) * d
    assert lhs <= mid < rhs, q
    assert (lhs == mid) == exact, q
    return t, s, exact


def render():
    lines = [
        "// Generated by scripts/gen_pow5_table.py; do not edit (run the script, and --check in CI).",
        "// kPow5[q + 342] = {high 64 bits, low 64 bits} of T(q), kPow5Shift[q + 342] = s(q), for q = -342 .. 308:",
        "// T(q) * 2^s(q) is 5^q rounded down to 128 significant bits (exact for 0 <= q <= 55). See the script.",
        "static constexpr int kPow5MinQ = %d, kPow5MaxQ = %d, kPow5ExactMaxQ = 55;" % (QMIN, QMAX),
        "static constexpr std::uint64_t kPow5[%d][2] = {" % (QMAX - QMIN + 1),
    ]
    shifts = []
    last_exact = None
    for q in range(QMIN, QMAX + 1):
        t, s, exact = entry(q)
        if exact:
            last_exact = q
        lines.append("    {0x%016xull, 0x%016xull},  // 5^%d" % (t >> 64, t & ((1 << 64) - 1), q))
        shifts.append(s)
    assert last_exact == 55
    lines.append("};")
    lines.append("static constexpr std::int16_t kPow5Shift[%d] = {" % len(shifts))
    for i in range(0, len(shifts), 16):
        lines.append("    " + ", ".join(str(v) for v in shifts[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("Pow5Table.inc differs from scripts/gen_pow5_table.py output", file=sys.stderr)
                return 1
        print("Pow5Table.inc matches (%d entries)" % (QMAX - QMIN + 1))
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.normpath(OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
