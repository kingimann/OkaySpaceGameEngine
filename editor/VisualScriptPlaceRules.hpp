inline VsPlace VsTranslateLegacy(const VsPlace& old) {
    if (!old.category) return {};
    for (const VsLegacyMove& m : kLegacyMoves) {
        if (std::strcmp(m.oldCategory, old.category) != 0) continue;
        if (std::strcmp(m.oldSub, old.subcategory ? old.subcategory : "") != 0) continue;
        VsPlace p = VsAt(m.category, m.sub);
        p.browse = old.browse;
        return p;
    }
    return {};
}

