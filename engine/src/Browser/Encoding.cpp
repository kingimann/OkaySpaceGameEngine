bool IsSingleByte(TextEncoding e) { return (int)e >= kFirstSingleByte && (int)e < kFirstSingleByte + kSingleByteCount; }

// The HTML standard's "ASCII whitespace" for the prescan: TAB, LF, FF, CR, SPACE.
bool PrescanSpace(unsigned char c) { return c == 0x09 || c == 0x0A || c == 0x0C || c == 0x0D || c == 0x20; }
bool AsciiAlpha(unsigned char c) { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z'); }

bool StartsNoCase(const std::string& s, std::size_t at, const char* word) {
    const std::size_t n = std::strlen(word);
    if (at + n > s.size()) return false;
    for (std::size_t k = 0; k < n; ++k) if (okay::str::LowerAsciiChar(s[at + k]) != word[k]) return false;
    return true;
}

// HTML 13.2.3.2 "get an attribute" over s[0, end): false when there is none (a '>' or the end of the bytes).
bool GetAttribute(const std::string& s, std::size_t end, std::size_t& pos, std::string& name, std::string& value) {
    name.clear();
    value.clear();
    while (pos < end && (PrescanSpace((unsigned char)s[pos]) || s[pos] == '/')) ++pos;
    if (pos >= end || s[pos] == '>') return false;
    bool sawSpace = false;
    for (;;) {   // the name
        if (pos >= end) return false;
        const unsigned char c = (unsigned char)s[pos];
        if (c == '=' && !name.empty()) { ++pos; break; }
        if (PrescanSpace(c)) { sawSpace = true; break; }
        if (c == '/' || c == '>') return true;
        name += okay::str::LowerAsciiChar((char)c);
        ++pos;
    }
    if (sawSpace) {
        while (pos < end && PrescanSpace((unsigned char)s[pos])) ++pos;
        if (pos >= end) return false;
        if (s[pos] != '=') return true;   // an attribute with no value
        ++pos;
    }
    while (pos < end && PrescanSpace((unsigned char)s[pos])) ++pos;
    if (pos >= end) return false;
    const unsigned char q = (unsigned char)s[pos];
    if (q == '"' || q == '\'') {
        for (++pos;; ++pos) {
            if (pos >= end) return false;
            if ((unsigned char)s[pos] == q) { ++pos; return true; }
            value += okay::str::LowerAsciiChar(s[pos]);
        }
    }
    if (q == '>') return true;
    for (;; ++pos) {
        if (pos >= end) return false;
        const unsigned char c = (unsigned char)s[pos];
        if (PrescanSpace(c) || c == '>') return true;
        value += okay::str::LowerAsciiChar((char)c);
    }
}

void AppendUtf16(std::string& out, const std::string& in, std::size_t start, bool bigEndian) {
    std::uint32_t lead = 0;   // a lead surrogate waiting for its trail
    std::size_t i = start;
    for (; i + 1 < in.size(); i += 2) {
        const unsigned char a = (unsigned char)in[i], b = (unsigned char)in[i + 1];
        const std::uint32_t unit = bigEndian ? (std::uint32_t)((a << 8) | b) : (std::uint32_t)((b << 8) | a);
        if (lead) {
            if (unit >= 0xDC00 && unit <= 0xDFFF) {
                okay::utf8::Append(out, 0x10000 + ((lead - 0xD800) << 10) + (unit - 0xDC00));
                lead = 0;
                continue;
            }
            okay::utf8::Append(out, okay::utf8::kReplacement);   // the lead had no trail; this unit is read on its own
            lead = 0;
        }
        if (unit >= 0xD800 && unit <= 0xDBFF) lead = unit;
        else if (unit >= 0xDC00 && unit <= 0xDFFF) okay::utf8::Append(out, okay::utf8::kReplacement);
        else okay::utf8::Append(out, unit);
    }
    if (lead || i < in.size()) okay::utf8::Append(out, okay::utf8::kReplacement);   // cut short
}

