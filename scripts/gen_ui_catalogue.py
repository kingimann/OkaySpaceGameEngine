#!/usr/bin/env python3
"""Write docs/ui_catalogue.md: every UI component, style, theme, icon and screen, with the counts and how they are counted.

The counts come straight from the data files in assets/ui/*.okaydata (the same files the engine embeds), so they can be checked:
    python3 scripts/gen_ui_catalogue.py           write docs/ui_catalogue.md
    python3 scripts/gen_ui_catalogue.py --check   fail when the file is out of date (also run by tests/test_ui_library4.cpp, which
                                                  compares these numbers with what the engine itself loads)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "assets", "ui")
OUT = os.path.join(ROOT, "docs", "ui_catalogue.md")


def parse(name):
    """Sections of one data file: (kind, name, kv dict, body lines), the same rules as engine/include/okay/UI/UILibData.hpp."""
    secs = []
    with open(os.path.join(DATA, name + ".okaydata"), encoding="utf-8") as f:
        for raw in f.read().split("\n"):
            raw = raw.rstrip()
            t = raw.strip()
            if not t or t.startswith("#"):
                continue
            if t.startswith("[") and t.endswith("]"):
                inner = t[1:-1]
                kind, _, nm = inner.partition(" ")
                secs.append([kind, nm.strip(), {}, []])
                continue
            if not secs:
                continue
            m = re.match(r"^([A-Za-z0-9_.]+)\s*=\s*(.*)$", t)
            if m:
                secs[-1][2][m.group(1)] = m.group(2).strip()
            else:
                secs[-1][3].append(raw)
    return secs


def of(secs, kind):
    return [s for s in secs if s[0] == kind]


def main():
    comps = of(parse("ui_components"), "component")
    styles_all = parse("ui_styles")
    styles = of(styles_all, "style")
    themes = of(parse("ui_themes"), "theme")
    icons = of(parse("ui_icons"), "icon")
    all_screens = parse("ui_screens")
    screens = of(all_screens, "screen")
    sections = of(all_screens, "section")

    # every component class must exist
    missing = []
    comp_dir = os.path.join(ROOT, "engine", "include", "okay", "Components")
    text = ""
    for fn in os.listdir(comp_dir):
        if fn.endswith(".hpp"):
            with open(os.path.join(comp_dir, fn), encoding="utf-8", errors="replace") as f:
                text += f.read()
    for c in comps:
        if not re.search(r"\bclass\s+%s\b" % re.escape(c[1]), text):
            missing.append(c[1])
    if missing:
        print("components in assets/ui/ui_components.okaydata without a class: " + ", ".join(missing), file=sys.stderr)
        return 1

    axis = {a: len(of(styles_all, a)) for a in ("shape", "fill", "border", "effect", "size", "density", "hover", "press", "disabled", "focus")}
    combos = axis["shape"] * axis["fill"] * axis["border"] * axis["effect"]
    derived = sum(1 for i in icons if any(l.strip().startswith("use ") for l in i[3]))
    variants = sum(len([v for v in s[2].get("variants", "").split("|") if v]) or 1 for s in screens)
    data_screens = sum(1 for s in screens if "native" not in s[2])
    builtin = sum(1 for t in themes if "preset" in t[2])
    state_looks = axis["hover"] + axis["press"] + axis["disabled"] + axis["focus"]

    L = []
    w = L.append
    w("# UI catalogue")
    w("")
    w("Generated by `python3 scripts/gen_ui_catalogue.py` from the data files in `assets/ui/` (the same files the engine embeds). Do not edit by hand;")
    w("`--check` fails when this file is out of date, and `tests/test_ui_library4.cpp` compares these numbers with what the engine loads.")
    w("")
    w("## The numbers")
    w("")
    w("These are the lines the test reads, so keep their form.")
    w("")
    w("- Components: %d" % len(comps))
    w("- Named styles: %d" % len(styles))
    w("- Themes: %d" % len(themes))
    w("- Icons: %d" % len(icons))
    w("- Screens: %d" % len(screens))
    w("- Screen variants: %d" % variants)
    w("- Style combinations: %d" % combos)
    w("")
    w("### How each number is counted")
    w("")
    w("| Thing | Count | Rule |")
    w("|---|---|---|")
    w("| Components | %d | one `[component]` entry per UI component class in `engine/include/okay/Components` (checked to exist) |" % len(comps))
    w("| Named styles | %d | one `[style]` entry: a named mix of shape, fill, border, effect, role and the four state looks. Two styles never share the same mix (a test checks), so these are distinct looks, not renamed copies |" % len(styles))
    w("| Style axes | %d shapes, %d fills, %d borders, %d effects, %d sizes, %d densities, %d state looks | the choices a style is made of; state looks are %d hover, %d pressed, %d disabled and %d focus |" % (axis["shape"], axis["fill"], axis["border"], axis["effect"], axis["size"], axis["density"], state_looks, axis["hover"], axis["press"], axis["disabled"], axis["focus"]))
    w("| Style combinations | %d | shapes x fills x borders x effects, computed, **not hand-made**: any of them can be set in the Inspector. With the %d sizes and %d densities that is %d option combinations |" % (combos, axis["size"], axis["density"], combos * axis["size"] * axis["density"]))
    w("| Themes | %d | one `[theme]` entry: %d are the built-in presets of the UI Theme component, %d are defined in data |" % (len(themes), builtin, len(themes) - builtin))
    w("| Icons | %d | one `[icon]` entry, drawn by our own code (no outside artwork): %d drawn from shapes and %d made by turning or mirroring another (arrow-left from arrow-right); every name is a different picture |" % (len(icons), len(icons) - derived, derived))
    w("| Screens | %d | one `[screen]` entry: %d are described in data and built by one builder, %d are older screens still built by their C++ function |" % (len(screens), data_screens, len(screens) - data_screens))
    w("| Screen variants | %d | for each screen the number of layout choices it lists (Centered, Left side, Right side, Dimmed backdrop); a screen without a list has one. A variant moves the card or adds a backdrop, the content is the same |" % variants)
    w("")
    w("Any screen can also be built under any of the %d themes (a theme-ready screen), which is %d screen-and-theme previews; that is a product, not a count of separate things." % (len(themes), len(screens) * len(themes)))
    w("")

    w("## Screens by section")
    w("")
    for sec in sections:
        inside = [s for s in screens if s[2].get("section") == sec[1]]
        w("### %s (%d)" % (sec[2].get("name", sec[1]), len(inside)))
        w("")
        w(sec[2].get("tip", ""))
        w("")
        w("| Screen | Variants | Tags | What it is |")
        w("|---|---|---|---|")
        for s in inside:
            v = [x for x in s[2].get("variants", "").split("|") if x]
            w("| %s | %s | %s | %s |" % (s[2].get("name", s[1]), ", ".join(v) if v else "1", s[2].get("tags", ""), s[2].get("desc", "")))
        w("")

    w("## Themes")
    w("")
    w("| Theme | Mode | Tags |")
    w("|---|---|---|")
    preset_mode = {"Light": "light", "Minimal": "light", "Fantasy": "light", "Modern Flat": "light", "Cartoon": "light"}
    for t in themes:
        mode = t[2].get("mode") or preset_mode.get(t[1], "dark")
        w("| %s | %s | %s |" % (t[1], mode + (" (built in)" if "preset" in t[2] else ""), t[2].get("tags", "")))
    w("")

    w("## Styles")
    w("")
    fams = []
    for s in styles:
        if s[2].get("family") not in fams:
            fams.append(s[2].get("family"))
    for f in fams:
        names = [s[1] for s in styles if s[2].get("family") == f]
        w("- **%s** (%d): %s" % (f, len(names), ", ".join(names)))
    w("")
    w("Axes: " + "; ".join("%s: %s" % (a, ", ".join(x[1] for x in of(styles_all, a))) for a in ("shape", "fill", "border", "effect", "size", "density", "hover", "press", "disabled", "focus")) + ".")
    w("")
    w("Not offered, because the renderer cannot draw them yet: stripe, noise and image fills, dashed borders.")
    w("")

    w("## Icons")
    w("")
    cats = []
    for i in icons:
        if i[2].get("category") not in cats:
            cats.append(i[2].get("category"))
    for c in cats:
        names = [i[1] for i in icons if i[2].get("category") == c]
        w("- **%s** (%d): %s" % (c, len(names), ", ".join(names)))
    w("")

    w("## Components")
    w("")
    ccats = []
    for c in comps:
        if c[2].get("category") not in ccats:
            ccats.append(c[2].get("category"))
    for cat in ccats:
        w("### %s" % cat)
        w("")
        w("| Component | What it does | Add it with |")
        w("|---|---|---|")
        for c in comps:
            if c[2].get("category") == cat:
                w("| %s | %s | %s |" % (c[1], c[2].get("desc", ""), "GameObject > UI (id %s)" % c[2]["menu"] if c[2].get("menu") else "Add Component"))
        w("")

    out = "\n".join(L) + "\n"
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != out:
            print("docs/ui_catalogue.md is out of date: run python3 scripts/gen_ui_catalogue.py", file=sys.stderr)
            return 1
        print("ui_catalogue up to date (%d components, %d styles, %d themes, %d icons, %d screens)" % (len(comps), len(styles), len(themes), len(icons), len(screens)))
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("wrote docs/ui_catalogue.md (%d components, %d styles, %d themes, %d icons, %d screens, %d variants)" % (len(comps), len(styles), len(themes), len(icons), len(screens), variants))
    return 0


sys.exit(main())
